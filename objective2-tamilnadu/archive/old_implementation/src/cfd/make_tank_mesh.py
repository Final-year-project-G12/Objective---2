"""
src/cfd/make_tank_mesh.py
============================
Writes a 2-D axisymmetric structured quad mesh of the storage tank in
Fluent/Gambit ASCII `.msh` format, for the G4 draw-case cross-check.

WHY WE GENERATE THE MESH INSTEAD OF DRAWING IT. The geometry is a
rectangle in (z, r) -- a vertical cylinder revolved about the axis -- so a
structured grid is exactly right and a mesher would add a GUI step with
nothing to decide. Writing the `.msh` directly also means the mesh is
reproducible from the tank dimensions in `system_config_shared.yaml`
rather than being a binary artifact nobody can regenerate.

AXISYMMETRIC, NOT PLANAR. Fluent's axisymmetric solver treats y as the
radius, so the cell volumes it computes are the true annular volumes
(2*pi*r*dr*dz). A planar 2-D reading of the same rectangle would model a
slab, not a cylinder, and every litre-based quantity would be wrong. The
mesh is written with y >= 0 and an `axis` boundary at y = 0 so Fluent can
only interpret it the intended way.

Boundary zones written:
    axis    y = 0            (axis of revolution)
    wall    y = R            (tank side wall)
    inlet   z = 0            (mains water enters at the bottom)
    outlet  z = H            (delivery leaves from the top)

Format reference: Fluent/Gambit mesh format -- section (10) nodes,
(13) faces with zone ids, (12) cells, (45) zone names. Faces carry
(left cell, right cell) with 0 meaning "outside the domain", which is what
makes a face a boundary face.
"""

import math
from pathlib import Path


def tank_dimensions(volume_L: float, height_to_diameter: float = 2.0):
    """Tank diameter and height for a given volume, holding H = k*D (the
    proportion this project's geometry module already assumes)."""
    v = volume_L / 1000.0
    # V = pi/4 * D^2 * H = pi/4 * k * D^3
    d = (4.0 * v / (math.pi * height_to_diameter)) ** (1.0 / 3.0)
    return d, height_to_diameter * d


def write_axisymmetric_tank_msh(path: Path, volume_L: float = 100.0,
                                 n_z: int = 120, n_r: int = 20,
                                 height_to_diameter: float = 2.0) -> dict:
    """Structured (n_z x n_r) quad mesh. Returns the geometry it used."""
    d, h = tank_dimensions(volume_L, height_to_diameter)
    radius = d / 2.0

    nz, nr = n_z + 1, n_r + 1            # node counts
    zs = [h * i / n_z for i in range(nz)]
    rs = [radius * j / n_r for j in range(nr)]

    def nid(i, j):                        # 1-based node id, i along z, j along r
        return i * nr + j + 1

    def cid(i, j):                        # 1-based cell id
        return i * n_r + j + 1

    n_nodes = nz * nr
    n_cells = n_z * n_r

    # ---- faces, grouped by zone so each zone is a contiguous id block ----
    interior, axis, wall, inlet, outlet = [], [], [], [], []

    for i in range(n_z):                  # faces with constant r (horizontal in r)
        for j in range(nr):
            a, b = nid(i, j), nid(i + 1, j)
            if j == 0:
                axis.append((a, b, cid(i, j), 0))
            elif j == n_r:
                wall.append((a, b, cid(i, j - 1), 0))
            else:
                interior.append((a, b, cid(i, j), cid(i, j - 1)))

    for j in range(n_r):                  # faces with constant z
        for i in range(nz):
            a, b = nid(i, j), nid(i, j + 1)
            if i == 0:
                inlet.append((a, b, cid(i, j), 0))
            elif i == n_z:
                outlet.append((a, b, cid(i - 1, j), 0))
            else:
                interior.append((a, b, cid(i, j), cid(i - 1, j)))

    zones = [("interior", 2, interior, "interior"),
             ("axis", 3, axis, "axis"),
             ("wall", 4, wall, "wall"),
             ("inlet", 5, inlet, "velocity-inlet"),
             ("outlet", 6, outlet, "pressure-outlet")]

    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="ascii") as f:
        f.write('(0 "Tank draw-case mesh, generated by src/cfd/make_tank_mesh.py")\n')
        f.write("(2 2)\n")                                   # 2-D
        f.write(f"(10 (0 1 {n_nodes:x} 0 2))\n")              # node declaration
        f.write(f"(12 (0 1 {n_cells:x} 0 0))\n")              # cell declaration
        n_faces = sum(len(z[2]) for z in zones)
        f.write(f"(13 (0 1 {n_faces:x} 0 0))\n")              # face declaration

        # nodes: x = z (axial), y = r (radial)
        f.write(f"(10 (1 1 {n_nodes:x} 1 2)(\n")
        for i in range(nz):
            for j in range(nr):
                f.write(f"{zs[i]:.9g} {rs[j]:.9g}\n")
        f.write("))\n")

        # cells: all quads (element type 3), one zone
        f.write(f"(12 (1 1 {n_cells:x} 1 3))\n")

        # faces, zone by zone; type 2 = linear (2-node) face
        first = 1
        for name, zid, faces, _bc in zones:
            if not faces:
                continue
            last = first + len(faces) - 1
            bc_type = 2 if name == "interior" else 3   # 2 interior, 3 wall-like
            f.write(f"(13 ({zid:x} {first:x} {last:x} {bc_type} 2)(\n")
            for a, b, c0, c1 in faces:
                f.write(f"{a:x} {b:x} {c0:x} {c1:x}\n")
            f.write("))\n")
            first = last + 1

        f.write("(45 (1 fluid fluid)())\n")
        for name, zid, faces, bc in zones:
            if faces:
                f.write(f"(45 ({zid} {bc} {name})())\n")

    return {"path": str(path), "volume_L": volume_L, "diameter_m": d, "height_m": h,
            "radius_m": radius, "n_cells": n_cells, "n_nodes": n_nodes,
            "n_z": n_z, "n_r": n_r}


