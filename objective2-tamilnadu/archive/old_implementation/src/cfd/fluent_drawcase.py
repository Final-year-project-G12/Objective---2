"""
src/cfd/fluent_drawcase.py
=============================
G4 CFD cross-check of the stratified tank model, in ANSYS Fluent.

THE CHECK. Manvitha's G4 runs a draw case in CFD and compares it to her
1-D multi-node tank: "CFD draw-case reproduction (30 L at 55 C over 20 L
at 25 C, 50 L tank)", scored on "Litres at or above 45 C" (her N=10 model
gave 22.5 L). The point is not to match CFD exactly -- a 1-D node stack
cannot -- but to show the node model does not invent or destroy
stratification during a draw, which is the one behaviour the whole
evening-delivery result rests on.

Tamil Nadu uses a 100 L tank, so the case is scaled while keeping her
60/40 hot/cold split: **60 L at 55 C over 40 L at 25 C**. Mains water
enters the bottom at 25 C and delivery leaves the top; the metric is the
litres drawn at or above 45 C, exactly as hers.

OpenFOAM -> ANSYS FLUENT is the deliberate substitution for this project.
Physics settings, and why:
  * 2-D AXISYMMETRIC (not planar): y is the radius, so cell volumes are
    the true annular volumes. A planar reading models a slab and every
    litre-based number would be wrong.
  * Gravity along -x (our mesh puts x along the tank axis, pointing up)
    with the BOUSSINESQ density model. Buoyancy is the entire mechanism
    holding the thermocline together; a constant-density run would let
    the draw smear it by advection alone and the comparison would be
    meaningless.
  * LAMINAR. The draw velocity in a 0.4 m tank is ~1e-4 m/s, so the bulk
    Reynolds number is order 10 -- a turbulence model here would add
    eddy diffusivity that is not physically present and would
    artificially destroy the thermocline.
  * Transient, with the timestep tied to the draw so the inflow crosses
    at most a fraction of a cell per step.

Fluent is driven through the TUI rather than the settings API because TUI
command paths are stable across Fluent versions while the Python settings
tree is not; a version mismatch there fails silently in ways that are hard
to notice. If Fluent cannot be launched (no licence, Student limits), the
journal is still written so the case is reproducible by hand -- it is not
silently skipped.
"""

import json
from pathlib import Path

from config import BASE_DIR, RESULTS_DIR
from src.cfd.make_tank_mesh import write_axisymmetric_tank_msh, tank_dimensions

CASE_DIR = BASE_DIR / "ansys_openfoam_case"
T_HOT_C, T_COLD_C = 55.0, 25.0
HOT_FRACTION = 0.60              # her 30 L of 50 L
TARGET_C = 45.0
TANK_L = 100.0
DRAW_LPM = 6.0                   # litres/min, a realistic household draw
KELVIN = 273.15


def build_journal(mesh_path: Path, geom: dict, out_dir: Path,
                   draw_lpm: float = DRAW_LPM) -> Path:
    """Writes the Fluent journal. Everything numeric here comes from the
    tank geometry or the case definition above -- nothing is invented."""
    radius, height = geom["radius_m"], geom["height_m"]
    area = 3.141592653589793 * radius ** 2
    # Draw rate -> inlet velocity. Mass is conserved, so the inlet
    # superficial velocity is the volumetric draw over the tank section.
    v_in = (draw_lpm / 1000.0 / 60.0) / area
    z_interface = height * (1.0 - HOT_FRACTION)   # hot sits ON TOP
    # One tank turnover, which is when the thermocline has fully swept out.
    t_total = TANK_L / draw_lpm * 60.0
    dz = height / geom["n_z"]
    dt = 0.25 * dz / max(v_in, 1e-12)             # <= 1/4 cell per step
    n_steps = int(round(t_total / dt))

    out_dir.mkdir(parents=True, exist_ok=True)
    report = (out_dir / "fluent_outlet_temperature.out").as_posix()
    jou = CASE_DIR / "g4_drawcase.jou"

    lines = [
        f'; G4 draw case: {TANK_L:.0f} L, {HOT_FRACTION*100:.0f}% at {T_HOT_C} C over {T_COLD_C} C',
        f'; generated by src/cfd/fluent_drawcase.py -- do not hand-edit',
        f'/file/read-case "{mesh_path.as_posix()}"',
        '/define/models/axisymmetric? yes',
        '/define/models/energy? yes no no no yes',
        '/define/models/viscous/laminar? yes',
        # water with a Boussinesq density so buoyancy holds the thermocline
        '/define/materials/change-create water-liquid water-liquid yes boussinesq 998.2 '
        'no no yes constant 4182 yes constant 0.6 yes constant 0.001003 no no no yes 0.000207 '
        'yes 300 no no',
        '/define/boundary-conditions/fluid fluid yes water-liquid no no no no 0 no 0 no 0 '
        'no 0 no 0 no 1 no no no no no',
        f'/define/operating-conditions/gravity? yes -9.81 0',
        f'/define/operating-conditions/operating-temperature {T_COLD_C + KELVIN}',
        # bottom inlet: mains water
        f'/define/boundary-conditions/velocity-inlet inlet no no yes yes no {v_in:.8g} no 0 '
        f'no {T_COLD_C + KELVIN}',
        '/define/boundary-conditions/pressure-outlet outlet yes no 0 no '
        f'{T_COLD_C + KELVIN} no yes no no',
        '/define/boundary-conditions/wall wall 0 no 0 no yes temperature no '
        f'{T_COLD_C + KELVIN} no no 1',
        '/solve/set/p-v-coupling 24',          # SIMPLE
        '/solve/set/discretization-scheme/pressure 12',
        '/solve/set/discretization-scheme/mom 1',
        '/solve/set/discretization-scheme/temperature 1',
        '/solve/initialize/set-defaults/temperature ' + f'{T_COLD_C + KELVIN}',
        '/solve/initialize/initialize-flow yes',
        # stratify: mark the upper region by x-coordinate and patch it hot
        '/adapt/set/min-number-cells 1',
        f'/adapt/mark-inout-rectangle yes no {z_interface:.8g} {height*1.001:.8g} '
        f'-0.001 {radius*1.001:.8g}',
        f'/solve/patch fluid () temperature {T_HOT_C + KELVIN}',
        # outlet temperature history is the whole measurement
        '/solve/monitors/surface/set-monitor outlet-T "Mass-Weighted Average" temperature '
        f'outlet () no yes yes "{report}" 1 no flow-time',
        f'/solve/set/time-step {dt:.8g}',
        f'/solve/dual-time-iterate {n_steps} 30',
        f'/file/write-case-data "{(out_dir / "g4_drawcase.cas.h5").as_posix()}"',
        '/exit yes',
    ]
    jou.write_text("\n".join(lines) + "\n", encoding="ascii")

    meta = {"mesh": mesh_path.as_posix(), "journal": jou.as_posix(),
            "report": report, "inlet_velocity_m_s": v_in, "dt_s": dt,
            "n_steps": n_steps, "t_total_s": t_total, "draw_lpm": draw_lpm,
            "z_interface_m": z_interface, "hot_C": T_HOT_C, "cold_C": T_COLD_C,
            "target_C": TARGET_C, **geom}
    (out_dir / "g4_drawcase_meta.json").write_text(json.dumps(meta, indent=2),
                                                    encoding="utf-8")
    return jou


def litres_above_target(report_path: Path, draw_lpm: float = DRAW_LPM,
                         target_C: float = TARGET_C) -> dict:
    """Integrates the outlet temperature history into 'litres delivered at
    or above the target' -- her G4 metric."""
    import numpy as np
    rows = []
    for line in Path(report_path).read_text(encoding="utf-8", errors="ignore").splitlines():
        parts = line.split()
        if len(parts) >= 2:
            try:
                rows.append((float(parts[-1]), float(parts[-2])))
            except ValueError:
                continue
    if not rows:
        return {"litres_above_target": float("nan"), "n_samples": 0}
    rows.sort()
    t = np.array([r[0] for r in rows])
    T = np.array([r[1] for r in rows]) - KELVIN
    dt = np.diff(t, prepend=t[0])
    lps = draw_lpm / 60.0
    litres = float(np.sum(dt[T >= target_C] * lps))
    return {"litres_above_target": litres, "n_samples": len(rows),
            "outlet_T_start_C": float(T[0]), "outlet_T_end_C": float(T[-1]),
            "t_end_s": float(t[-1])}


def run(launch: bool = True, draw_lpm: float = DRAW_LPM):
    out_dir = RESULTS_DIR / "tamilnadu" / "g4_cfd"
    mesh_path = CASE_DIR / "tank_drawcase_100L.msh"
    geom = write_axisymmetric_tank_msh(mesh_path, volume_L=TANK_L)
    jou = build_journal(mesh_path, geom, out_dir, draw_lpm)
    print(f"mesh    {mesh_path}  ({geom['n_cells']} cells)")
    print(f"journal {jou}")

    if not launch:
        print("\nnot launching Fluent (launch=False). Run the journal by hand:")
        print(f"  File > Read > Journal...  ->  {jou}")
        return None

    try:
        import ansys.fluent.core as pyfluent
    except ImportError:
        print("pyfluent not installed -- run the journal in the Fluent GUI instead")
        return None

    print("\nlaunching Fluent (2D, double precision)...")
    solver = pyfluent.launch_fluent(mode="solver", dimension=2, precision="double",
                                    processor_count=1, ui_mode="no_gui")
    try:
        for cmd in jou.read_text(encoding="ascii").splitlines():
            cmd = cmd.strip()
            if not cmd or cmd.startswith(";") or cmd.startswith("/exit"):
                continue
            try:
                solver.execute_tui(cmd)
            except Exception as e:
                print(f"  TUI step failed: {cmd[:70]}...\n    {type(e).__name__}: {e}")
    finally:
        try:
            solver.exit()
        except Exception:
            pass

    report = Path(out_dir / "fluent_outlet_temperature.out")
    if report.exists():
        res = litres_above_target(report, draw_lpm)
        (out_dir / "g4_cfd_result.json").write_text(json.dumps(res, indent=2),
                                                     encoding="utf-8")
        print(f"\nCFD litres >= {TARGET_C} C: {res['litres_above_target']:.2f} L "
              f"({res['n_samples']} samples)")
        return res
    print("\nno outlet report produced -- see the Fluent output above")
    return None


if __name__ == "__main__":
    import sys
    run(launch="--no-launch" not in sys.argv)
