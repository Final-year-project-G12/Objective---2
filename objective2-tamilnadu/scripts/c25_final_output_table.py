"""
scripts/c25_final_output_table.py
=================================
Writes docs/OBJ2_FINAL_OUTPUT.md: the plain "final design per regime" table plus where every output lives, with every number read from the
sealed Objective-2 contract (results/common100L_<hash>/o3_environment_contract_tamilnadu.json). Nothing is typed by hand.

Usage:  python scripts/c25_final_output_table.py
"""
import glob
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
c = json.loads(Path(glob.glob(str(ROOT / "results/common100L_*/o3_environment_contract_tamilnadu.json"))[0]).read_text(encoding="utf-8"))
D, g, pl = c["static_design_per_regime"], c["one_shot_test"]["gates"], c["plant"]
pcm_pk, w_pk = float(g["pcm_peak_under_65C"].split()[1]), float(g["water_peak_under_75C"].split()[1])

t1 = "\n".join(f"| {d['regime_id']} | **PCM tank** | {d['selected_pcm']} | {d['capsule_inner_radius_m'] * 1000:.0f} mm radius | {d['n_capsules']} | "
               f"{d['pcm_volume_fraction'] * 100:.1f} % | {d['arrangement']} | {d['pcm_mass_kg']:.1f} kg |" for d in D)
t2 = "\n".join(f"| {d['regime_id']} | {d['selected_pcm']} | {d['one_shot_test_2006_2010']['gain_mean_kWh']:.0f} kWh/yr | "
               f"{d['one_shot_test_2006_2010']['years_pcm_better']} | +{d['one_shot_test_2006_2010']['overheat_extra_hours_per_year']:.0f} h/yr |" for d in D)

M1 = [(0, "m1"), (1, "m1_regime1"), (2, "m1_regime2")]


def m1_row(k, folder):
    fig = ROOT / "results" / folder / "figures"
    n_png, n_mp4 = len(list(fig.glob("*.png"))) if fig.exists() else 0, len(list(fig.glob("*.mp4"))) if fig.exists() else 0
    state = f"{n_png} figures + {n_mp4} animations" if (n_png or n_mp4) else "not built"
    return f"| {k} | {D[k]['selected_pcm']} | `results/{folder}/figures/` | {state} |"


t3 = "\n".join(m1_row(k, f) for k, f in M1)

md = f"""# Objective 2 — final output (Tamil Nadu)

*Plant: {pl['tank_volume_L']:.0f} L tank, {pl['collector_area_m2']:.1f} m² collector, {pl['demand_daily_total_L']:.0f} L/day of 45 °C water. Generated by `scripts/c25_final_output_table.py` from the sealed Objective-2 contract (`results/common100L_<hash>/o3_environment_contract_tamilnadu.json`); every number is read from it.*

## 1. Final design per regime (the main output)

| Regime | Recommendation | PCM | Capsule size | Capsules | PCM share of tank | Layout | PCM mass |
|---|---|---|---|---|---|---|---|
{t1}

All designs use a flow of {D[0]['nominal_flow_kg_s']:.3f} kg/s. The hottest temperatures stay inside the safety limits: PCM about {pcm_pk:.0f} °C (limit 65 °C) and water about {w_pk:.0f} °C (limit 75 °C).

Tamil Nadu has three climate regimes, and the PCM tank was recommended in all three; no regime fell back to a water-only tank. The capsule size is the inner radius (outer diameter {D[0]['capsule_outer_diameter_mm']:.1f} mm). Both the 40 mm radius and the 40 % PCM-share cap are at their upper limits, so this is the corner of the search box.

## 2. What the PCM tank delivers (one-shot test on 2006–2010, run once)

| Regime | PCM | Extra heat over a plain tank | Years PCM wins | Extra overheat-guard hours |
|---|---|---|---|---|
{t2}

The PCM tank beats the plain tank on delivered energy in every test year of every regime, but spends more hours in the overheat guard, because the capsules take the place of water in the fixed {pl['tank_volume_L']:.0f} L tank.

## 3. Where the MATLAB and ANSYS outputs are

**MATLAB (checkpoint M1), one folder per regime.** Each has the seven what-if designs (the optimum, max of everything, min of everything, a real funnel finalist, only 30 capsules, 10 % and 50 % of the optimum) shown as: a discharge test, three real weather days (clear, average, cloudy), an annual ranking, the four Objective-1 PCMs, and three animated tank cut-aways. It visualises the simulator's own output; it is not a separate MATLAB model.

| Regime | PCM | Folder | Contents |
|---|---|---|---|
{t3}

Data behind the figures: the CSV files and `manifest.json` in the parent folder (`results/m1/`, `results/m1_regime1/`, `results/m1_regime2/`). Rebuild: `python scripts/c20_m1_export.py --regime k`, then `M1_DIR=results/<folder> matlab -batch "run('matlab_m1/m1_main.m')"`.

**ANSYS Fluent seven-criteria study: regime 0 only** (`ansys/criteria_0_optimal_reference/` … `ansys/criteria_6_50pct_of_optimal/`, summary in `ansys/criteria_common/`). Whole-tank and single-capsule discharge demos exist for all three regimes (`ansys/fluent_tank_discharge.py`, `ansys/fluent_discharge_demo.py`).
"""
(ROOT / "docs" / "OBJ2_FINAL_OUTPUT.md").write_text(md, encoding="utf-8")
print(md)
