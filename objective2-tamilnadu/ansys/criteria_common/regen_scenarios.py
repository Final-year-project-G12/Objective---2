"""
ansys/criteria_common/regen_scenarios.py   (level L8 step 1)
=============================================================
Rewrites ansys/criteria_common/scenarios.py for the COMMON-PLANT rebuild from the Objective 2 funnel winner of regime 0
(results/c16_funnel_winners.csv): the optimum and the six alternatives of the Fluent study (max of everything, min of everything, a working-but-not-optimal
design, only 30 capsules, 10 % and 50 % of the optimal PCM), defined with the same rules as before, with the 40 % fraction cap, flow 0.030 kg/s for the optimum
and the same 2-D proxy rule (drawn capsules = round(N * 34 / N_opt), drawn radius = 0.5 R_in). The old file is kept once as scenarios_legacy_300L.py.
All kWh numbers in the text are produced later by run_node_model.py from the optimiser's own evaluator, not typed here.
Usage: python ansys/criteria_common/regen_scenarios.py
"""
import math
import shutil
from pathlib import Path

import pandas as pd

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
V_TANK, WALL = 0.100, 0.0008


def v_outer(r):
    return 4.0 / 3.0 * math.pi * (r + WALL) ** 3


def main():
    win = pd.read_csv(ROOT / "results/c16_funnel_winners.csv")
    w = win[win.regime == 0].iloc[0]
    if w.recommendation != "PCM":
        raise SystemExit("regime 0 recommendation is not PCM; Fluent criteria are defined around a PCM optimum - decide manually")
    R, F, arr, N, pcm = float(w.R_in_m), float(w.fraction), w.arrangement, int(w.N), w.pcm
    # 'working but not optimal': a real evaluated select-year candidate of the winning pair at roughly 70 % of the optimal gain
    ev = pd.read_csv(ROOT / "results/c16_select_eval_all.csv")
    pool = ev[(ev.regime == 0) & (ev.pair == w.pair) & (ev.S0 == True)]                        # noqa: E712
    pool = pool[(pool.N != N)]
    if len(pool):
        c = pool.iloc[(pool.g_window_mean - 0.70 * float(w.select_g_window_mean)).abs().argsort()].iloc[0]
        r3, f3, note3 = float(c.R_in_m), float(c.fraction), f"a real evaluated candidate of the funnel pool (N = {int(c.N)})"
    else:
        r3, f3, note3 = R, 0.77 * N * v_outer(R) / V_TANK, "77 % of the optimal capsule count (no other feasible candidate in the pool)"

    def fr(n):
        return n * v_outer(R) / V_TANK

    legacy = HERE / "scenarios_legacy_300L.py"
    if not legacy.exists():
        shutil.copy(HERE / "scenarios.py", legacy)
    txt = f'''"""
ansys/criteria_common/scenarios.py   (REGENERATED by regen_scenarios.py - common plant 100 L / 2.0 m2 / 175 L/day)
=====================================================================================================
The seven "what-if" design criteria (the optimum + six alternatives) for the whole-tank discharge study, and how each 3-D design becomes the 2-D Fluent picture.
Regime 0, {pcm}, 100 L tank. Optimum = the Objective 2 funnel winner (results/c16_funnel_winners.csv).

THE 2-D PROXY RULE: the Fluent mesh is a planar slice, which cannot hold the real 3-D capsule count, so every scenario is drawn with
    drawn capsules = round( N_3D * 34 / N_OPT_3D )        (the optimum is exactly the 34-capsule picture)
    drawn inner R   = R_in_3D * 0.5
Energy numbers come from the node model (the optimiser's own evaluator); the Fluent picture shows SHAPE and TIME behaviour only. Cross-check, never validation.
"""
import math

V_TANK_M3 = 0.100
WALL_M = 0.0008
N_OPT_3D = {N}
N_OPT_2D = 34
R_SCALE_2D = 0.5

PCM = "{pcm}"
REGIME = 0


def v_outer(r_in):
    return 4.0 / 3.0 * math.pi * (r_in + WALL_M) ** 3


def frac_for_count(r_in, n):
    return n * v_outer(r_in) / V_TANK_M3


def drawn_count(n3d):
    return max(1, int(round(n3d * N_OPT_2D / N_OPT_3D)))


OPT = dict(R_in={R!r}, fraction={F!r}, flow=0.030, arrangement="{arr}")

SCENARIOS = [
    dict(key="criteria_0_optimal_reference", title="0. OPTIMAL (reference)", design=dict(OPT),
         rule="The Objective 2 funnel winner for regime 0 (S0/S1/S2 frozen before the select years were run).",
         why_not_optimal="It IS the optimum - reference for every other run."),
    dict(key="criteria_1_max_all", title="1. MAX of every parameter",
         design=dict(R_in=0.040, fraction=0.40, flow=0.050, arrangement="staggered"),
         rule="Every knob at its upper bound: R_in 40 mm, PCM fraction 40 %, flow 0.050 kg/s, staggered packing.",
         why_not_optimal="See node_model_results.json: compare its gain, overheat hours and PCM mass with the optimum; a difference inside the repeatability band is a tie broken by the funnel's S2 rule."),
    dict(key="criteria_2_min_all", title="2. MIN of every parameter",
         design=dict(R_in=0.010, fraction=0.02, flow=0.010, arrangement="single-layer"),
         rule="Every knob at its lower bound: R_in 10 mm, PCM fraction 2 %, flow 0.010 kg/s, single-layer packing.",
         why_not_optimal="Almost no PCM, so almost no latent storage: see node_model_results.json for the gain relative to the optimum."),
    dict(key="criteria_3_ok_not_optimal", title="3. NOT optimal, but working",
         design=dict(R_in={r3!r}, fraction={f3!r}, flow=0.030, arrangement="{arr}"),
         rule="{note3}.",
         why_not_optimal="Passes the hard gates and beats the plain tank but delivers less than the optimum: see node_model_results.json."),
    dict(key="criteria_4_only_30_capsules", title="4. YOUR WISH: only 30 capsules",
         design=dict(R_in={R!r}, fraction=frac_for_count({R!r}, 30), flow=0.030, arrangement="{arr}"),
         rule="Only 30 real capsules (optimal radius, optimal flow, optimal arrangement).",
         why_not_optimal="A fraction of the optimal PCM mass: the store is used up sooner; see node_model_results.json."),
    dict(key="criteria_5_10pct_of_optimal", title="5. 10 % of the optimal PCM",
         design=dict(R_in={R!r}, fraction=frac_for_count({R!r}, {max(1, round(0.10 * N))}), flow=0.030, arrangement="{arr}"),
         rule="N = 10 % of the optimal capsule count ({max(1, round(0.10 * N))} capsules; radius, flow, arrangement kept optimal).",
         why_not_optimal="Very little PCM: see node_model_results.json for the gain relative to the repeatability band."),
    dict(key="criteria_6_50pct_of_optimal", title="6. 50 % of the optimal PCM",
         design=dict(R_in={R!r}, fraction=frac_for_count({R!r}, {max(1, round(0.50 * N))}), flow=0.030, arrangement="{arr}"),
         rule="N = 50 % of the optimal capsule count ({max(1, round(0.50 * N))} capsules; radius, flow, arrangement kept optimal).",
         why_not_optimal="Half the PCM: see node_model_results.json for how the gain scales with PCM mass."),
]
'''
    (HERE / "scenarios.py").write_text(txt, encoding="utf-8")
    print("scenarios.py regenerated: optimum", pcm, f"R_in={R*1000:.1f} mm fraction={F:.3f} N={N} {arr}")

    # 40 % fraction cap in the folder builder; node-model funnel inputs from the new funnel
    b = HERE / "build_criteria_folders.py"
    s = b.read_text(encoding="utf-8").replace("hi = math.floor(0.30 * V_TANK_M3 / v + 1e-9)", "hi = math.floor(0.40 * V_TANK_M3 / v + 1e-9)")
    b.write_text(s, encoding="utf-8")
    m = HERE / "run_node_model.py"
    s = m.read_text(encoding="utf-8")
    old = s[s.index('    sel = json.loads((ROOT / "results" / "g10_selection_r0.json")'):s.index("    w = _weather(REGIME, YEAR, PURPOSE)")]
    new = '''    win = pd.read_csv(ROOT / "results" / "c16_funnel_winners.csv")
    w0 = win[win.regime == 0].iloc[0]
    band_g, band_d = float(w0.band_kWh), 0.0                      # core repeatability band (c15); S2 = lowest overheat among the tied
    ev = pd.read_csv(ROOT / "results" / "c16_select_eval_all.csv")
    pool = ev[(ev.regime == 0) & (ev.pair == w0.pair) & (ev.S0 == True)].rename(columns={"g_window_mean": "g_window", "d_overheat_mean": "d_overheat"})  # noqa: E712
    g_best = pool.g_window.max()
    s0 = pool[pool.g_window >= g_best - band_g]
    d_floor = s0.d_overheat.min()

'''
    s = s.replace(old, new).replace("YEAR = 2021", "YEAR = 2020").replace("select years\n2021-2023", "select years\n2020-2021").replace("node-model on select years 2021-23", "node-model on select years 2020-21")
    m.write_text(s, encoding="utf-8")
    print("build_criteria_folders.py cap 0.40; run_node_model.py reads the new funnel")


if __name__ == "__main__":
    main()
