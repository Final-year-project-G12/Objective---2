PHT = os.path.expanduser("~/OpenFOAM/OpenFOAM-PHT53IACP")
BASE = os.path.join(PHT, "examples/porousHeatTransferFoam/PCMValidations/GR27")
def _find_db():
    here = os.path.dirname(os.path.abspath(__file__))
    cur = here
    for _ in range(6):
        for cand in (cur, os.path.join(cur, "objective2-rajasthan")):
            f = os.path.join(cand, "data", "objective1", "pcm_database_rajasthan.csv")
            if os.path.exists(f):
                return f
        cur = os.path.dirname(cur)
    return os.environ.get("PCM_DB", "pcm_database_rajasthan.csv")


DB_DEFAULT = _find_db()

HEADER = """/*--------------------------------*- C++ -*----------------------------------*\\
  generated by pht_make_case.py (Objective 2, Rajasthan) -- edit the generator
\\*---------------------------------------------------------------------------*/
"""


def ff(cls, obj, body, loc=None):
    l = f'    location    "{loc}";\n' if loc else ""
    return (HEADER + "FoamFile\n{\n    version     2.0;\n    format      ascii;\n"
            f"    class       {cls};\n{l}    object      {obj};\n}}\n\n{body.rstrip()}\n")


def wr(d, rel, txt):
    p = os.path.join(d, rel)
    os.makedirs(os.path.dirname(p), exist_ok=True)
    with open(p, "w", newline="\n") as f:
        f.write(txt)


def base_files(out):
    """Copy numerics that are known to work from the shipped GR27 case."""
    for rel in ("system/fvSchemes", "system/fvSolution", "constant/fvOptions"):
        os.makedirs(os.path.dirname(os.path.join(out, rel)), exist_ok=True)
        shutil.copy(os.path.join(BASE, rel), os.path.join(out, rel))


def write_case(out, *, H, A, ncell, a, k1, k2, alpha, chi, htf, pcm, T_init, T_in, q_vol,
               t_end, probes_m, dt=1.0, write_every=60, meta=None, tin_table=None,
               T_init_solid=None, T_init_fluid=None):
    """htf: dict(Cp, rho, mu, Pr).  pcm: dict(kappa, rho, CpS, CpL, Tph, T1, T2, Hf)."""
    os.makedirs(out, exist_ok=True)
    base_files(out)
    T_init_s = T_init if T_init_solid is None else T_init_solid
    T_init_f = T_init if T_init_fluid is None else T_init_fluid
    if tin_table:      # time-varying inlet water temperature [(t_s, T_K), ...]
        rows = " ".join(f"({t:.6g} {T:.6g})" for t, T in tin_table)
        floor_bc = ("type uniformFixedValue; value uniform %.9g; "
                    "uniformValue table (%s);" % (tin_table[0][1], rows))
    else:
        floor_bc = f"type fixedValue; value uniform {T_in:.9g};"
    side = math.sqrt(A)
    wr(out, "system/blockMeshDict", ff("dictionary", "blockMeshDict", f"""
scale   1;
vertices
(
    (0 0 0) ({side:.9g} 0 0) ({side:.9g} {H:.9g} 0) (0 {H:.9g} 0)
    (0 0 {side:.9g}) ({side:.9g} 0 {side:.9g}) ({side:.9g} {H:.9g} {side:.9g}) (0 {H:.9g} {side:.9g})
);
blocks ( hex (0 1 2 3 4 5 6 7) (1 {ncell} 1) simpleGrading (1 1 1) );
edges ();
boundary
(
    floor {{ type patch; faces ((1 5 4 0)); }}
    ceiling {{ type patch; faces ((3 7 6 2)); }}
    frontAndBack {{ type empty; faces ((0 4 7 3) (2 6 5 1) (0 3 2 1) (4 5 6 7)); }}
);
mergePatchPairs ();
"""))
    wr(out, "constant/g", ff("uniformDimensionedVectorField", "g",
                             "dimensions [0 1 -2 0 0 0 0];\nvalue (0 0 0);", "constant"))
    wr(out, "constant/transportProperties", ff("dictionary", "transportProperties", f"""
a        {a:.9g};
chi      {chi};
KD       {1.0 / k1:.9g};     // 1/k1
F        {k2:.9g};           // k2
HTcoef   {alpha:.9g};        // alpha [W/m3K]
""", "constant"))
    wr(out, "constant/thermophysicalProperties.fluid", ff("dictionary", "thermophysicalProperties.fluid", f"""
thermoType
{{
    type            heRhoThermo;
    mixture         pureMixture;
    transport       const;
    thermo          hConst;
    equationOfState rhoConst;
    specie          specie;
    energy          sensibleEnthalpy;
}}
pRef            100000;
mixture
{{
    specie          {{ molWeight 18.0; }}
    thermodynamics  {{ Cp {htf['Cp']:.9g}; Hf 0; }}
    equationOfState {{ rho {htf['rho']:.9g}; }}
    transport       {{ mu {htf['mu']:.9g}; Pr {htf['Pr']:.9g}; }}
}}
""", "constant"))
    wr(out, "constant/thermophysicalProperties.solid", ff("dictionary", "thermophysicalProperties.solid", f"""
thermoType
{{
    type            heSolidThermo;
    mixture         pureMixture;
    transport       constIso;
    thermo          hMeltingSolidificationCubic;
    equationOfState rhoConst;
    specie          specie;
    energy          sensibleEnthalpy;
}}
mixture
{{
    specie          {{ molWeight 50; }}
    transport       {{ kappa {pcm['kappa']:.9g}; }}
    thermodynamics
    {{
        Hf    {pcm['Hf']:.9g};
        CpS   {pcm['CpS']:.9g};
        CpL   {pcm['CpL']:.9g};
        Tph   {pcm['Tph']:.9g};
        T1    {pcm['T1']:.9g};
        T2    {pcm['T2']:.9g};
    }}
    equationOfState {{ rho {pcm['rho']:.9g}; }}
}}
updateT no;
""", "constant"))
    wr(out, "0.orig/T.fluid", ff("volScalarField", "T.fluid", f"""
dimensions [0 0 0 1 0 0 0];
internalField uniform {T_init_f:.9g};
boundaryField
{{
    floor        {{ {floor_bc} }}
    ceiling      {{ type zeroGradient; }}
    frontAndBack {{ type empty; }}
}}
"""))
    wr(out, "0.orig/T.solid", ff("volScalarField", "T.solid", f"""
dimensions [0 0 0 1 0 0 0];
internalField uniform {T_init_s:.9g};
boundaryField
{{
    floor        {{ type zeroGradient; }}
    ceiling      {{ type zeroGradient; }}
    frontAndBack {{ type empty; }}
}}
"""))
    wr(out, "0.orig/U", ff("volVectorField", "U", f"""
dimensions [0 1 -1 0 0 0 0];
internalField uniform (0 0 0);
boundaryField
{{
    floor        {{ type flowRateInletVelocity; volumetricFlowRate {q_vol:.9g}; }}
    ceiling      {{ type fluxCorrectedVelocity; }}
    frontAndBack {{ type empty; }}
}}
"""))
    wr(out, "0.orig/p", ff("volScalarField", "p", """
dimensions [1 -1 -2 0 0 0 0];
internalField uniform 0;
boundaryField
{
    floor        { type fixedFluxExtrapolatedPressure; }
    ceiling      { type fixedValue; value uniform 0; }
    frontAndBack { type empty; }
}
"""))
    pts = "\n        ".join(f"({side / 2:.6g} {y:.6g} {side / 2:.6g})" for y in probes_m)
    wr(out, "system/controlDict", ff("dictionary", "controlDict", f"""
application     porousHeatTransferFoam;
startFrom       startTime;
startTime       0;
stopAt          endTime;
endTime         {t_end:.9g};
deltaT          {dt};
writeControl    adjustableRunTime;
writeInterval   {write_every};
purgeWrite      0;
writeFormat     ascii;
writePrecision  7;
writeCompression off;
timeFormat      general;
timePrecision   7;
runTimeModifiable true;
adjustTimeStep  no;
maxCo           450;

functions
{{
    probesBed
    {{
        type            probes;
        libs            (sampling);
        writeControl    timeStep;
        writeInterval   {max(1, int(30 / dt))};
        fields          (T.solid T.fluid);
        probeLocations
        (
        {pts}
        );
    }}
}}
""", "system"))
    wr(out, "Allrun", "#!/bin/sh\ncd \"${0%/*}\" || exit 1\n. $WM_PROJECT_DIR/bin/tools/RunFunctions\n"
                      "runApplication blockMesh\nrestore0Dir\nrunApplication $(getApplication)\n")
    os.chmod(os.path.join(out, "Allrun"), 0o755)
    if meta is not None:
        with open(os.path.join(out, "case_meta.json"), "w") as f:
            json.dump(meta, f, indent=2)


