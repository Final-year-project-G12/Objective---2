def nallusamy(a):
    # values from the paper Sec. 4.3 (Eq. 32) / shipped `water` example; shell folded in
    w = (54.2e-3) ** 3 / (55e-3) ** 3
    kappa = w * 0.5 * (0.4 + 0.15) + (1 - w) * 0.44
    rho = w * 0.5 * (861 + 778) + (1 - w) * 940
    CpS = (w * 819.5 * 1850 + (1 - w) * 940 * 1900) / 824.68
    CpL = (w * 819.5 * 2384 + (1 - w) * 940 * 1900) / 824.68
    T1, T2 = 273 + 59, 273 + 61                      # example file; paper text prints 332/334 K
    Hf = w * 819.5 / 824.68 * (213e3 - 0.5 * (CpS + CpL) * (T2 - T1))
    H, Deq = 0.46, 0.36
    A = math.pi * (Deq / 2) ** 2
    meta = dict(case="nallusamy_water", source="Fetsov & Lutsenko 2023 Sec.4.3 / shipped water example",
                a=0.5, H=H, D_equiv=Deq, kappa=kappa, rho=rho, CpS=CpS, CpL=CpL, Hf=Hf, T1=T1, T2=T2,
                alpha=3000, k1=1e-5, k2=127.3, Q_L_min=2.0, T_in=a.T_in, T_init=a.T_init)
    write_case(a.out, H=H, A=A, ncell=100, a=0.5, k1=1e-5, k2=127.3, alpha=3000.0, chi=0.5,
               htf=dict(Cp=4190.0, rho=1000.0, mu=0.6e-3, Pr=4.5),
               pcm=dict(kappa=kappa, rho=rho, CpS=CpS, CpL=CpL, Tph=333.0, T1=T1, T2=T2, Hf=Hf),
               T_init=a.T_init, T_in=a.T_in, q_vol=2.0 / 1000 / 60, t_end=160 * 60,
               probes_m=[0.25 * H, 0.5 * H, 0.75 * H, 0.99 * H], meta=meta)
    print(json.dumps(meta, indent=1))


def load_pcm(db, name):
    with open(db, encoding="utf-8-sig") as f:
        for r in csv.DictReader(f):
            if r["name"].strip().lower() == name.strip().lower() or name.strip().lower() in r["name"].lower():
                g = lambda k, alt=None: float(r[k] if r.get(k) not in ("", None) else r[alt])
                return dict(name=r["name"], Tm=g("Tm_C"), L=g("latent_heat_kJ_kg") * 1e3,
                            rho_s=g("density_solid_kg_m3", "density_liquid_kg_m3"),
                            cp_s=g("Cp_solid_kJ_kgK", "Cp_avg_kJ_kgK") * 1e3,
                            cp_l=g("Cp_liquid_kJ_kgK", "Cp_avg_kJ_kgK") * 1e3, k=g("TC_W_mK"))
    raise SystemExit(f"PCM {name} not in {db}")


def rajasthan(a):
    p = load_pcm(a.db, a.pcm)
    V = a.tank_L / 1000.0
    D = (4 * V / (math.pi * 2.0)) ** (1 / 3)         # H/D = 2 (frozen)
    H = 2 * D
    A = math.pi / 4 * D * D
    v_cap = math.pi * a.d ** 3 / 6
    phi_pcm = a.n * v_cap / V                         # PCM volume fraction
    if not 0 < phi_pcm < 0.5:
        raise SystemExit(f"PCM fraction {phi_pcm:.3f} out of range")
    por = 1.0 - phi_pcm                               # void fraction seen by the water
    a_s = 6 * phi_pcm / a.d                           # specific area  [m2/m3]
    # water-side h: same Wakao-Kaguei / superficial velocity as src/simulation
    mu = 2.414e-5 * 10 ** (247.8 / (40 + 273.15 - 140))
    u = a.mdot / 1000.0 / A
    re = max(1000.0 * u * a.d / mu, 1e-6)
    h_w = (2 + 1.1 * re ** 0.6 * 4.3 ** (1 / 3)) * 0.63 / a.d
    r = a.d / 2
    r_tot = 1 / h_w + 0.0008 / 205.0 + a.phi * r / (5 * p["k"])
    alpha = a_s / r_tot
    k1 = a.d ** 2 * por ** 3 / (150 * (1 - por) ** 2)
    k2 = 1.75 * (1 - por) / (a.d * por ** 3)
    Tm = p["Tm"] + 273.15
    T1, T2 = Tm - 1.0, Tm + 1.0
    cpS, cpL = p["cp_s"], p["cp_l"]
    Hf = p["L"] - 0.5 * (cpS + cpL) * (T2 - T1)       # same band convention as the grey-box
    T_init = Tm - a.t_init_below
    T_in = Tm + a.dT
    meta = dict(case="rajasthan_bed", pcm=p["name"], Tm_C=p["Tm"], d_m=a.d, N=a.n, mdot_kg_s=a.mdot,
                dT_K=a.dT, phi_scale=a.phi, tank_L=a.tank_L, D_tank_m=D, H_tank_m=H,
                D_over_d=D / a.d, pcm_volume_fraction=phi_pcm, porosity=por, a_s_m2_m3=a_s, h_w=h_w,
                Re_p=re, alpha_W_m3K=alpha, k1=k1, k2=k2, Hf=Hf,
                note="D/d < 7-8 is outside the paper's validated range" if D / a.d < 7 else "within validated range")
    tin = None
    if a.tin_csv:
        tin = []
        for ln in open(a.tin_csv):
            if ln.strip() and not ln.startswith("#") and not ln[0].isalpha():
                t_s, T_k = ln.split(",")[:2]
                tin.append((float(t_s), float(T_k)))
        meta["tin_csv"] = a.tin_csv
    meta.update(T1=T1, T2=T2)
    write_case(a.out, H=H, A=A, ncell=a.ncell, a=por, k1=k1, k2=k2, alpha=alpha, chi=0.5,
               htf=dict(Cp=4186.0, rho=1000.0, mu=mu, Pr=4.3),
               pcm=dict(kappa=p["k"], rho=p["rho_s"], CpS=cpS, CpL=cpL, Tph=Tm, T1=T1, T2=T2, Hf=Hf),
               T_init=T_init, T_in=T_in, q_vol=a.mdot / 1000.0 / A,
               t_end=(a.t_end_s if a.t_end_s else a.t_end_h * 3600),
               probes_m=[0.05 * H, 0.25 * H, 0.5 * H, 0.75 * H, 0.97 * H], meta=meta, dt=a.dt,
               write_every=a.write_every, tin_table=tin,
               T_init_solid=a.T_init_solid_K, T_init_fluid=a.T_init_fluid_K)
    print(json.dumps(meta, indent=1))


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sp = ap.add_subparsers(dest="cmd", required=True)
    n = sp.add_parser("nallusamy")
    n.add_argument("--out", required=True)
    n.add_argument("--T-init", type=float, default=298.0, help="paper prints Ta = 298 K; shipped example uses 305 K")
    n.add_argument("--T-in", type=float, default=343.0)
    r = sp.add_parser("rajasthan")
    r.add_argument("--out", required=True)
    r.add_argument("--pcm", default="RT44HC")
    r.add_argument("--d", type=float, default=0.06)
    r.add_argument("--n", type=int, default=30)
    r.add_argument("--mdot", type=float, default=0.03)
    r.add_argument("--dT", type=float, default=15.0, help="inlet water above Tm [K]")
    r.add_argument("--phi", type=float, default=1.0, help="scale on internal resistance r/(5k)")
    r.add_argument("--tank-L", type=float, default=50.0)
    r.add_argument("--t-init-below", type=float, default=15.0)
    r.add_argument("--t-end-h", type=float, default=8.0)
    r.add_argument("--ncell", type=int, default=100)
    r.add_argument("--db", default=DB_DEFAULT)
    r.add_argument("--tin-csv", default=None, help="csv t_s,T_K inlet water temperature (time-varying)")
    r.add_argument("--T-init-solid-K", type=float, default=None)
    r.add_argument("--T-init-fluid-K", type=float, default=None)
    r.add_argument("--t-end-s", type=float, default=None)
    r.add_argument("--dt", type=float, default=1.0)
    r.add_argument("--write-every", type=float, default=60.0)
    a = ap.parse_args()
    (nallusamy if a.cmd == "nallusamy" else rajasthan)(a)


if __name__ == "__main__":
    main()
