#!/usr/bin/env python3
"""
pht_make_case.py -- cases for porousHeatTransferFoam (Fetsov & Lutsenko 2023)

Standard library only; runs inside WSL (python3) because the base files are
copied from the cloned solver repository ($FOAM_PHT53_EXAMPLES).

  python3 pht_make_case.py nallusamy --out DIR [--T-init 298] [--T-in 343]
      Paper Sec. 4.3 water-HTF case (Nallusamy et al. 2007 experiment) with the
      values printed in the paper and in the shipped `water` example.

  python3 pht_make_case.py rajasthan --out DIR --pcm RT44HC --d 0.06 --n 30
          --mdot 0.03 --dT 15 --phi 1.0 [--tank-L 50] [--t-end-h 8]
      One-dimensional bed in the project's 50 L tank (H/D = 2): water HTF,
      spherical capsules, O1-database PCM enthalpy curve (+/-1 K band).
      alpha_eff = a_s / (1/h_w + t_Al/k_Al + phi * r/(5 k_pcm))
      phi = 1  : the grey-box's frozen lumped resistance;
      phi < 1  : CFD-calibrated (results/cfd_doe_results*.csv).

LIMITS (state them): continuum (volume-averaged) model; the paper validates it
down to tank-diameter / capsule-diameter ~ 7-8. D/d for our designs is
0.317/0.04 = 8 ... 0.317/0.08 = 4, so the large-capsule end is OUTSIDE the
validated range. alpha is an input; intra-capsule convection is not resolved.
"""
