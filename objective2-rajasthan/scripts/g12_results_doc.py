"""
scripts/g12_results_doc.py
=============================
G12 - writes docs/04_RESULTS.md. All tables are generated from files under results/ (the same files the
registry points at), so no number in that document is typed by hand. Only the narrative sentences are hand-written, and they
state qualitative readings that the tables beside them show.
Usage: python scripts/g12_results_doc.py   (run scripts/g12_registry.py first)
"""

import json
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

OUT = Path("results")
DOC = Path("docs/04_RESULTS.md")


def md(df):
    cols = list(df.columns)
    lines = ["| " + " | ".join(cols) + " |", "|" + "|".join("---" for _ in cols) + "|"]
    for r in df.itertuples(index=False):
        lines.append("| " + " | ".join(str(x) for x in r) + " |")
    return "\n".join(lines)


def main():
    sel = [json.loads((OUT / f"g10_selection_r{c}.json").read_text(encoding="utf-8")) for c in range(3)]
    held = pd.read_csv(OUT / "g10_heldout_results.csv")
    gc = pd.read_csv(OUT / "g9_grid_check.csv")
    ss = pd.read_csv(OUT / "g9_seed_stability.csv")
    lock = json.loads((OUT / "held_out_test.lock").read_text())
    s = []
    s.append("# Results - Objective 2, Rajasthan (current pipeline)\n")
    s.append("Generated by `scripts/g12_results_doc.py` from the saved files named under each table; do not edit by hand. Every value is also a row "
             "in `results/results_registry.csv`. Gains are PAIRED differences against a water-only tank at the same flow, weather year, "
             "demand, shield and tank model. Energy figures are E_del,45 (energy delivered at the 45 C target) in kWh per year, `g_window` for the "
             "18:00-09:00 window and `g_annual` for the whole year. `d_overheat` is shield-hours of the PCM tank minus the water-only tank.\n")

    s.append("**Version.** Sections 1-4 are the v3 results (PCM fraction cap 30 %, `docs/PROGRESS.md` section 26; tested once on the untouched years "
             "2011-2015). Sections 1b and 5b-5f are the diagnostics of the six issues, run on the v1 (cap 20 %) designs and years; they describe the v1 "
             "result, their source files are unchanged in `results/`,. "
             "They have not been re-run on the v3 designs." + "\n")
    s.append("## 1. Chosen design per regime (select years 2021-2023)\n")
    s.append("Source: `results/g10_selection_r{0,1,2}.json`.\n")
    rows = []
    for c, j in enumerate(sel):
        k = j["chosen"]
        rows.append({"regime": c, "PCM": k["pcm"], "R_in mm": f"{k['R_in_m'] * 1000:.1f}", "PCM fraction": f"{k['fraction']:.3f}",
                     "capsules": int(k["N"]), "flow kg/s": f"{k['flow']:.3f}", "arrangement": k["arrangement"],
                     "g_window kWh": f"{k['g_window']:.1f}", "g_annual kWh": f"{k['g_annual']:.1f}",
                     "d_overheat h": f"{k['d_overheat']:.0f}", "PCM peak C": f"{k['t_pcm_max']:.1f}", "PCM kg": f"{k['pcm_mass_kg']:.2f}",
                     "tau_serve gain h": f"{k.get('gain_tau_serve_h', float('nan')):+.3f}",
                     "band g_window kWh": f"{j['band']['g_window']:.1f}", "S0 / S1 / S2": f"{j['n_S0_indistinguishable_on_g_window']} / {j['n_S1']} / {j['n_S2']}"})
    s.append(md(pd.DataFrame(rows)) + "\n")
    bnd = pd.read_csv(OUT / "g9_boundary_check.csv")
    cap = bnd[bnd.bound.str.contains("30 % cap") & bnd.pair.str.endswith("_p1")].set_index("pair").share_of_front
    rad = bnd[bnd.bound.str.contains("40 mm end") & bnd.pair.str.endswith("_p1")].set_index("pair").share_of_front
    s.append("Reading: the chosen designs are still at the edge of the approved box: inner radius 39.5-40 mm and PCM fraction 28-30 % against the new 30 % cap. "
             "Share of the final rank-1 front at the 30 % cap / at the 40 mm radius end: "
             + "; ".join(f"regime {i} {100 * cap.get(f'r{i}_p1', 0):.0f} % / {100 * rad.get(f'r{i}_p1', 0):.0f} %" for i in range(3))
             + " (`g9_boundary_check.csv`). Raising the cap from 20 % to 30 % therefore did not remove the boundary limitation in regimes 0 and 2; "
             "the optimiser still asks for as much PCM as the box allows. The gain on the primary window metric is far above its band in each regime. The night-serve "
             "duration gain is about zero or negative. `d_overheat` is positive, but it mixes two different things (section 1b). The S0 set is the set "
             "of candidates the band cannot tell apart on `g_window`; the final pick inside it follows the written tie-break order, so the exact "
             "flow and capsule count should not be over-interpreted.\n")

    sp = pd.concat([pd.read_csv(OUT / f"g13_shield_split_r{c}.csv") for c in range(3)])
    s.append("## 1b. Shield hours split into water side and PCM side [v1 diagnostic, cap 20 %] (issue 4)\n")
    s.append("Source: `results/g13_shield_split_r{0,1,2}.csv` (script `scripts/g13_issue4_shield_split.py`). `d_overheat`, as stored in every G9-G11 "
             "file, is (water-side + PCM-side shield hours of the PCM tank) minus the water-only tank's water-side hours. The PCM-side term is a per-node "
             "throttle at 62 C that a water-only tank cannot have, so `d_overheat` is positive by construction. Like for like, the water-side term is "
             "`d_shield_water_h`. Chosen designs, mean of the select years 2021-2023 (hours per year); the optimisation objective f3 is unchanged.\n")
    t = (sp[(sp.role == "chosen") & (sp.purpose == "select")].groupby("regime")[
        ["shield_water_h_pcm", "shield_water_h_plain", "d_shield_water_h", "shield_pcm_h", "d_overheat_as_stored", "t_water_max_pcm_C", "t_water_max_plain_C"]]
         .mean().round(1).reset_index())
    t.columns = ["regime", "water-side h, PCM tank", "water-side h, water-only", "d_shield_water h", "PCM-side throttle h", "d_overheat h (stored)",
                 "peak water C, PCM", "peak water C, water-only"]
    s.append(md(t) + "\n")
    nneg = int((sp.d_shield_water_h < 0).sum())
    s.append(f"Reading: in {nneg} of {len(sp)} design-years (chosen designs and the best design of every other O1 PCM, explore and select years) the PCM tank has "
             "FEWER water-side shield hours than the water-only tank, and its water peak stays closer to the 72 C guard. The PCM-side throttle hours are "
             "real and are reported separately: they mean the capsules are full and charging is held back, not that a limit was exceeded (PCM peak stays "
             "below 65 C in every kept design). The v3 held-out file carries the same split (section 2).\n")

    s.append("## 2. Held-out test, untouched years 2011-2015 (v3, run once)\n")
    s.append(f"Source: `results/g10_heldout_results.csv`, run id `{lock['run_id']}`, lock `results/held_out_test.lock`. "
             "Chosen design and the best design of every other O1 PCM of the regime, all five years, nothing dropped. The v1 test on 2024-2025 (cap 20 %) used those years, which are labelled used.\n")
    t = held[["regime", "role", "pcm", "year", "g_window", "g_annual", "d_overheat", "t_pcm_max", "t_water_max", "gain_tau_serve_mean_h"]].copy()
    for col, nd in (("g_window", 1), ("g_annual", 1), ("d_overheat", 0), ("t_pcm_max", 1), ("t_water_max", 1), ("gain_tau_serve_mean_h", 3)):
        t[col] = t[col].round(nd)
    t.columns = ["regime", "role", "PCM", "year", "g_window kWh", "g_annual kWh", "d_overheat h", "PCM peak C", "water peak C", "tau_serve gain h"]
    s.append(md(t) + "\n")
    m = held.groupby(["regime", "role", "pcm"]).agg(g=("g_window", "mean"), gmin=("g_window", "min"), sw=("shield_water_h", "mean"),
                                                      sh=("shield_pcm_h", "mean"), pw=("plain_shield_water_h", "mean")).reset_index()
    ch = m[m.role == "chosen"].set_index("regime")
    lines = []
    for c, j in enumerate(sel):
        oth = m[(m.regime == c) & (m.role != "chosen")]
        top = oth.loc[oth.g.idxmax()]
        lines.append(f"regime {c}: chosen {ch.loc[c, 'g']:.1f} kWh/yr (select years {j['chosen']['g_window']:.1f}; weakest test year {ch.loc[c, 'gmin']:.1f}); best other PCM "
                     f"{top.pcm} {top.g:.1f} (difference {ch.loc[c, 'g'] - top.g:+.1f} kWh against a band of {j['band']['g_window']:.1f})")
    s.append("Reading (means over the five test years): " + "; ".join(lines) + ". "
             f"Peak PCM temperature over all designs and years {held.t_pcm_max.max():.1f} C (limit 65), peak water {held.t_water_max.max():.1f} C (limit 75). "
             "Like-for-like shield hours (mean per year, chosen designs): "
             + "; ".join(f"regime {c} water side {ch.loc[c, 'sw']:.0f} h against {ch.loc[c, 'pw']:.0f} h for the water-only tank, PCM-side throttle {ch.loc[c, 'sh']:.0f} h" for c in range(3))
             + ". The test years differ from the select years (2011-2015 against 2021-2023), so the level is not a like-for-like comparison with the select "
             "value; the checks that matter are that the gain stays far above the band in every test year and how the chosen design compares with the best "
             "other PCM." + "\n")

    s.append("## 3. Optimiser checks (G9)\n")
    s.append("Sources: `results/g9_grid_check.csv` (dense grid vs final front, rank-1 PCM of each regime), `g9_seed_stability.csv`.\n")
    g = gc[["pair", "n_final_front", "hv_ratio_final_over_grid", "eps_g_window", "eps_g_annual", "eps_d_overheat", "band_g_window",
            "band_g_annual", "band_d_overheat", "within_band"]].round(2)
    s.append(md(g) + "\n")
    q = ss[["pair", "hv_spread", "hv_band", "spread_within_band"]].copy()
    q["hv_spread"] = q.hv_spread.round(0).astype(int)
    q["hv_band"] = q.hv_band.round(0).astype(int)
    s.append(md(q) + "\n")
    s.append("In v3 the box-vertex step is part of the recipe from the start (5 rounds, then vertices and 3 more rounds), and all three regimes pass the dense-grid check within the band at the first attempt. "
             "The grid contains the vertices by construction, so the pass is not fully independent evidence (`docs/PROGRESS.md` sections 11.1-11.3 and 24 for the v1 history)." + "\n")

    s.append("## 4. Ablations and controls (G11)\n")
    s.append("Source: `results/g11_ablation_r{0,1,2}.csv`, explore years 2016-2020, `g_window` in kWh.\n")
    rows = []
    for c in range(3):
        d = pd.read_csv(OUT / f"g11_ablation_r{c}.csv")
        v = lambda b, lv: float(d[(d.block == b) & (d.level == lv)].g_window.iloc[0])  # noqa: E731
        rows.append({"regime": c, "chosen": round(v("base", "chosen"), 1),
                     "fraction 2 %": round(v("count", "f0.02"), 1), "fraction 10 %": round(v("count", "f0.10"), 1),
                     "flow 0.010": round(v("flow", "q0.010"), 1), "flow 0.050": round(v("flow", "q0.050"), 1),
                     "anchor bottom": round(v("arrangement_anchor", "staggered|bottom"), 1),
                     "anchor top": round(v("arrangement_anchor", "staggered|top"), 1),
                     "latent heat = 0": round(v("pos_control_latent_zero", "L=0"), 1),
                     "synthetic Tm 45 C": round(v("pos_control_Tm45_synthetic", "Tm=45C"), 1)})
    s.append(md(pd.DataFrame(rows)) + "\n")
    ab = []
    for c in range(3):
        d = pd.read_csv(OUT / f"g11_ablation_r{c}.csv")
        base = d[d.block == "base"].iloc[0]
        x = d[(d.block == "arrangement_anchor") & (d.arrangement == base.arrangement)].g_window
        cnt = d[d.block == "count"].set_index("level").g_window
        ab.append((c, float(x.max() - x.min()), float(cnt["f0.30"] - cnt["f0.25"]), float(cnt["f0.30"] - cnt["f0.20"])))
    s.append("Negative controls (water-only invariance to design variables, determinism, inert wall conductivity) all returned zero difference. "
             "The latent-heat = 0 control drops the gain below zero in every regime, so the metric does respond to the PCM. From the chosen designs the PCM-fraction x2 "
             "control is clipped by the 30 % cap (N stays at the cap count), so it adds nothing here; the interior-anchor version of it (section 5b) was run for the v1 designs. "
             "The fraction sweep shows the gain still rising at the cap: from 25 % to 30 % the gain rises by "
             + ", ".join(f"{u:+.1f} kWh (regime {c})" for c, _, u, _ in ab) + " and from 20 % to 30 % by "
             + ", ".join(f"{w:+.1f}" for _, _, _, w in ab) + " kWh, all far above the band, so the cap is still limiting at 30 %. "
             "Thickness at constant mass has valid geometry only at 40 mm in regimes 1 and 2 (smaller radii are geometry-infeasible at that mass). "
             "Moving the capsule stack over bottom / centre / top changes the chosen arrangement's gain by "
             + ", ".join(f"{r:.1f} kWh (regime {c})" for c, r, _, _ in ab) + " (bands in section 1).\n")
    s.append("## 5b. Controls re-run from an interior anchor [v1 diagnostic, cap 20 %] (issue 5)\n")
    s.append("Source: `results/g14_controls_r{0,1,2}.csv` (script `scripts/g14_issue5_controls.py`), explore years 2016-2020, `g_window` in kWh. "
             "Anchor declared before the run: R_in 25 mm, outer PCM fraction 10 % (70 capsules), flow 0.030 kg/s, staggered, stack centre, the regime's chosen "
             "PCM. Thickness is varied at constant INNER PCM volume (count scales with (25/R)^3); the outer volume, and so the displaced water, still changes "
             "a little with R (0.097-0.115 of the tank) and is shown. `x2` uses the largest count inside the 20 % cap (139 capsules); a first attempt with "
             "140 capsules (20.1 %) was rejected by the cap and is recorded in the progress log.\n")
    rows = []
    for c in range(3):
        d = pd.read_csv(OUT / f"g14_controls_r{c}.csv")
        band = float(pd.read_csv(OUT / "wp6_band.csv").query(f"scope == 'r{c}' and objective == 'g_window'").band.iloc[0])
        base = float(d[d.block == "base"].g_window.iloc[0])
        row = {"regime": c, "band": round(band, 1), "anchor g_window": round(base, 1)}
        for blk, lv, name in (("thickness_const_mass", "R10", "R 10 mm"), ("thickness_const_mass", "R15", "R 15 mm"), ("thickness_const_mass", "R20", "R 20 mm"),
                              ("thickness_const_mass", "R30", "R 30 mm"), ("thickness_const_mass", "R40", "R 40 mm"),
                              ("fraction", "x0.5", "fraction x0.5"), ("fraction", "x2", "fraction x2")):
            row[name] = f"{float(d[(d.block == blk) & (d.level == lv)].g_window.iloc[0]) - base:+.1f}"
        rows.append(row)
    s.append("Change in `g_window` (kWh) relative to the anchor:\n")
    s.append(md(pd.DataFrame(rows)) + "\n")
    s.append("Reading: the fraction control now responds (x2 adds 31-44 kWh, x0.5 removes 20-25 kWh, all beyond the band), so the metric and the pipeline "
             "can see a change in PCM amount. Thickness is informative below about 25 mm (R 10 and 15 mm clearly worse in every regime) and flat above it: "
             "R 30 and 40 mm differ from 25 mm by less than the band in every regime, so the 40 mm optimum is not distinguishable from 30 mm at this anchor.\n")
    s.append("## 5c. Dependence on the stack position [v1 diagnostic, cap 20 %] (issue 6)\n")
    s.append("Source: `results/g15_anchor_r{0,1,2}.csv` (script `scripts/g15_issue6_anchor.py`): the frozen chosen design and the best design of every "
             "other O1 PCM, re-evaluated with the capsule stack anchored at the tank bottom, centre (the model default, `configs/design_space.yaml`, key stack_anchor) "
             "and top; select years 2021-2023, `g_window` in kWh, paired with the water-only tank (which does not depend on the anchor). Nothing was "
             "re-optimised, and no position is preferred for giving a better result.\n")
    an = pd.concat([pd.read_csv(OUT / f"g15_anchor_r{c}.csv") for c in range(3)])
    sa = an[an.purpose == "select"].groupby(["regime", "role", "pcm", "pcm_rank", "anchor"]).g_window.mean().reset_index()
    bands = pd.read_csv(OUT / "wp6_band.csv")
    rows = []
    for c in range(3):
        band = float(bands.query(f"scope == 'r{c}' and objective == 'g_window'").band.iloc[0])
        x = sa[(sa.regime == c) & (sa.role == "chosen")].set_index("anchor").g_window
        row = {"regime": c, "band": round(band, 1), "bottom": round(x["bottom"], 1), "centre": round(x["center"], 1), "top": round(x["top"], 1),
               "range": round(x.max() - x.min(), 1)}
        for a in ("bottom", "center", "top"):
            y = sa[(sa.regime == c) & (sa.anchor == a)]
            best_pcm = y.groupby("pcm").g_window.max().sort_values(ascending=False)
            row[f"best PCM at {a}"] = best_pcm.index[0].replace("�", "").replace("savE", "savE") + f" (+{best_pcm.iloc[0] - best_pcm.iloc[1]:.1f} over 2nd)"
            row[f"regret of chosen design at {a}"] = round(float(y.g_window.max() - y[y.role == "chosen"].g_window.iloc[0]), 1)
        rows.append(row)
    s.append(md(pd.DataFrame(rows)) + "\n")
    lo = an.groupby(["regime", "role", "pcm", "anchor", "purpose"]).g_window.mean().min()
    s.append(f"Reading: the sign of the gain survives every position (smallest mean gain of any kept design at any position: {lo:.1f} kWh against bands of "
             "10-16 kWh), so 'PCM helps on the window metric' does not depend on the anchor. The LEVEL does: the chosen design's range over the three positions is "
             "45-56 kWh, three to six times the band, and the top position gives the highest values, in line with the 'near the top' statements that the "
             "Eldokaishi 2022 introduction attributes to others and with the abstract of Izgi and Arslan 2022 (see the progress log, section 21) - which is "
             "no reason to adopt it. The best PCM of each regime is the same at all three positions, but its margin over the runner-up is inside the band in "
             "regimes 0 and 2 at the bottom and centre (regime 1 separates its top two at every position). 'Regret' is how much better the best of the four saved designs is than the chosen one at "
             "that position: in regimes 1 and 2 with the stack at the bottom another design of the same PCM is 22 kWh better, so the chosen designs there are not anchor-robust "
             "(its flow and size were selected for the centre position).\n")
    s.append("## 5d. Evening-scenario decomposition [v1 diagnostic, cap 20 %] (issue 3)\n")
    s.append("Source: `results/g16_serve_r{0,1,2}.csv` and `g16_serve_plain_40L_r{0,1,2}.csv` (script `scripts/g16_issue3_serve.py`): the frozen chosen "
             "design, select years 2021-2023, night scenario on every 15th day (18:00 start, no sun, project demand to 09:00). Cases: `pcm` (the design), "
             "`plain` (the official baseline, same 50 L tank and flow), `pcm_L0` (latent heat set to zero, so the capsules act as sensible storage), and "
             "`plain_40L` (DIAGNOSTIC ONLY, not a baseline: a water-only tank whose water volume is reduced by the capsule volume, to isolate displacement). "
             "`E_del45` is the plan's WP1 energy metric, sum of m cp (min(T_out, 45 C) - T_mains) over the scenario, i.e. delivery up to the 45 C target.\n")
    sv = pd.concat([pd.read_csv(OUT / f"g16_serve_r{c}.csv") for c in range(3)] +
                   [pd.read_csv(OUT / f"g16_serve_plain_40L_r{c}.csv") for c in range(3)])
    sv = sv[sv.valid == True]  # noqa: E712
    sm = sv.groupby(["regime", "case"])[["tau_serve_mean_h", "serve_frac_45_mean", "serve_E_del45_mean_kWh", "tau_hold_mean_h"]].mean()
    rows = []
    for c in range(3):
        g = lambda case, k: float(sm.loc[(c, case), k])  # noqa: E731
        rows.append({"regime": c,
                     "tau_serve h: plain / 40 L water / L=0 / PCM": " / ".join(f"{g(k, 'tau_serve_mean_h'):.3f}" for k in ("plain", "plain_40L", "pcm_L0", "pcm")),
                     "serve fraction: plain / 40 L / L=0 / PCM": " / ".join(f"{g(k, 'serve_frac_45_mean'):.3f}" for k in ("plain", "plain_40L", "pcm_L0", "pcm")),
                     "E_del45 kWh: plain / 40 L / L=0 / PCM": " / ".join(f"{g(k, 'serve_E_del45_mean_kWh'):.3f}" for k in ("plain", "plain_40L", "pcm_L0", "pcm")),
                     "tau_hold h: plain / 40 L / L=0 / PCM": " / ".join(f"{g(k, 'tau_hold_mean_h'):.1f}" for k in ("plain", "plain_40L", "pcm_L0", "pcm")),
                     "PCM minus plain: tau_serve h, E_del45 kWh": f"{g('pcm', 'tau_serve_mean_h') - g('plain', 'tau_serve_mean_h'):+.3f}, {g('pcm', 'serve_E_del45_mean_kWh') - g('plain', 'serve_E_del45_mean_kWh'):+.3f}",
                     "PCM minus 40 L water: tau_serve h, E_del45 kWh": f"{g('pcm', 'tau_serve_mean_h') - g('plain_40L', 'tau_serve_mean_h'):+.3f}, {g('pcm', 'serve_E_del45_mean_kWh') - g('plain_40L', 'serve_E_del45_mean_kWh'):+.3f}"})
    s.append(md(pd.DataFrame(rows)) + "\n")
    s.append("Reading: the zero or negative `tau_serve` gain is the net of two opposite effects. Taking about 20 % of the 50 L tank for capsules removes water, "
             "which alone shortens the serve time (water-only tank with 40 L: shorter than the 50 L tank in every regime); the PCM then adds back time "
             "relative to that displacement-matched tank, but not enough to pass the 50 L tank. The energy delivered up to 45 C in the same scenario is HIGHER "
             "with PCM than with the 50 L water-only tank in every regime and select year, and the sensible-only (L = 0) case is lower than the water-only tank, "
             "so that energy gain comes from the latent heat. What remains true and is reported: the volume of water delivered at 45 C or above in the evening "
             "(serve fraction) and the time to the first drop below 45 C are NOT improved relative to the same fixed 50 L tank, because the capsules take water volume.\n")
    s.append("## 5e. Widened-bound diagnostic [v1 diagnostic, cap 20 %] (issue 2)\n")
    s.append("Source: `results/g17_widen_r{0,1,2}.csv` (script `scripts/g17_issue2_widen.py`). WP6 boundary-artefact rule: relax each bound the optimum sits on "
             "inside a diagnostic run and see whether `g_window` moves by more than the band. The approved box is NOT changed; the wider geometry bounds exist only "
             "inside the script. Frozen chosen design of each regime, explore years 2016-2020, stack centre, exact water-only run at the same flow; "
             "change in `g_window` (kWh) relative to the chosen design's explore value. Radii above 40 mm have no capsule-size source in the files read.\n")
    rows = []
    for c in range(3):
        w = pd.read_csv(OUT / f"g17_widen_r{c}.csv")
        base = float(json.loads((OUT / f"g10_selection_r{c}.json").read_text(encoding="utf-8"))["chosen"]["explore_g_window"])
        band = float(bands.query(f"scope == 'r{c}' and objective == 'g_window'").band.iloc[0])
        row = {"regime": c, "band": round(band, 1)}
        for blk, lv, name in (("A_radius", "R30", "R 30 mm"), ("A_radius", "R45", "R 45 mm"), ("A_radius", "R50", "R 50 mm"),
                              ("B_fraction", "f0.25", "fraction 25 %"), ("B_fraction", "f0.30", "fraction 30 %"), ("B_fraction", "f0.40", "fraction 40 %"),
                              ("D_flow", "q0.080", "flow 0.080 kg/s")):
            v = float(w[(w.block == blk) & (w.level == lv)].g_window.iloc[0]) - base
            row[name] = f"{v:+.1f}"
        row["all feasible (65 C / 75 C)"] = bool(w.feasible_65_75.all())
