#!/usr/bin/env python3
"""Generate an axisymmetric (wedge) OpenFOAM-ESI v2406 case for melting/solidification inside ONE
spherical PCM capsule: buoyantPimpleFoam + Boussinesq liquid + solidificationMeltingSource
(Voller-Prakash enthalpy-porosity, Darcy damping in the mushy zone).

Usage:
  python scripts/make_capsule_case.py --design r0 --scenario charge_70 [--cells 40] [--out cases/]
  python scripts/make_capsule_case.py --scenario V0_tan2009            # literature benchmark (Tan et al. 2009)
  options: --cu 1e5 --q 0.01 (Darcy constants)  --mu-scale / --beta-scale (property range)  --tag NAME

The case is the CFD counterpart of the simulator's lumped capsule node (R = r/(5k), x2 liquid
convection, Tm +/- 1 K band). It is NOT the whole tank. Model-to-model comparison only.
Rewritten 2026-10-29 after the first real run: the mesh/thermo/fvOptions layout is taken from the case that
already ran on this machine (openfoam_cfd/scripts/make_case.py); the first draft used keys ESI v2406 does not have
(Tsol/Tliq, system/fvOptions). Differences to the simulator, all stated in docs/07_OPENFOAM_VALIDATION.md:
  * melting is ISOTHERMAL at Tm (ESI's fvOption has one `Tmelt`); the simulator uses a Tm +/- 1 K band
  * rho0 = density_solid (the simulator's capsule mass is density_solid x inner volume) so the energy
    capacity of the CFD capsule equals the simulator's
  * one conductivity (database TC_W_mK) and mean cp are used for both phases
Refuses to write a case while any required property in configs/rj_cases.yaml is null.
"""
import argparse, json, math, os, sys
import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
K0 = 273.15
HDR = r"""/*--------------------------------*- C++ -*----------------------------------*\
  rj_openfoam | generated by scripts/make_capsule_case.py | edit the generator, not this file
\*---------------------------------------------------------------------------*/
"""
REQ = ["Tm_C", "latent_J_kg", "k_solid", "k_liquid", "rho_solid", "rho_liquid",
       "cp_solid", "cp_liquid", "mu_Pa_s", "beta_1_K"]


def fail(msg):
    sys.exit(f"[make_capsule_case] {msg}")


def foam(cls, obj, body):
    return (HDR + f"FoamFile\n{{\n    version 2.0;\n    format ascii;\n    class {cls};\n    object {obj};\n}}\n"
            "// * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * //\n\n"
            + body.strip() + "\n")


def block_mesh(R, n, wedge_deg, grading=0.4):
    """Half-disk butterfly (core square + 3 arc blocks) rotated +/- wedge/2 about the x axis (capsule axis = x)."""
    hw = math.radians(wedge_deg / 2.0)
    s = 0.5 * R
    c45 = math.cos(math.radians(45.0))
    P = {"P0": (-s, 0.0), "P1": (s, 0.0), "P2": (s, s), "P3": (-s, s),
         "C0": (-R, 0.0), "C1": (R, 0.0), "C2": (R * c45, R * c45), "C3": (-R * c45, R * c45)}
    verts, vid = [], {}

    def add(name, plane):
        x, y = P[name]
        key = (name, plane if y > 1e-15 else 0)
        if key not in vid:
            verts.append((x, y * math.cos(hw), plane * y * math.sin(hw)))
            vid[key] = len(verts) - 1
        return vid[key]

    def V(name, plane):
        return vid[(name, plane if P[name][1] > 1e-15 else 0)]

    nc = max(4, int(round(n / 2)))
    nr = max(4, n - nc)
    blocks = [("core", ["P0", "P1", "P2", "P3"], (nc, nc), (1, 1)),
              ("right", ["P1", "C1", "C2", "P2"], (nr, nc), (grading, 1)),
              ("top", ["P3", "P2", "C2", "C3"], (nc, nr), (1, grading)),
              ("left", ["C0", "P0", "P3", "C3"], (nr, nc), (1.0 / grading, 1))]
    hexes = []
    for nm, names, (n1, n2), (g1, g2) in blocks:
        ids = [add(q, -1) for q in names] + [add(q, +1) for q in names]
        hexes.append((nm, ids, n1, n2, g1, g2))

    def arc(a, b, ang):
        m = (R * math.cos(math.radians(ang)), R * math.sin(math.radians(ang)))
        return [f"    arc {V(a, pl)} {V(b, pl)} ({m[0]:.9g} {m[1] * math.cos(hw):.9g} {pl * m[1] * math.sin(hw):.9g})"
                for pl in (-1, +1)]

    edges = arc("C1", "C2", 22.5) + arc("C2", "C3", 90.0) + arc("C3", "C0", 157.5)
    out = ["scale 1;\n", "vertices\n(\n"] + [f"    ({x:.9g} {y:.9g} {z:.9g})\n" for x, y, z in verts] + [");\n\nblocks\n(\n"]
    for nm, ids, n1, n2, g1, g2 in hexes:
        out.append(f"    // {nm}\n    hex ({' '.join(map(str, ids))}) ({n1} {n2} 1) simpleGrading ({g1:g} {g2:g} 1)\n")
    out.append(");\n\nedges\n(\n" + "\n".join(edges) + "\n);\n\nboundary\n(\n")
    out.append("    wall\n    {\n        type wall;\n        faces\n        (\n")
    for a, b in (("C1", "C2"), ("C2", "C3"), ("C3", "C0")):
        out.append(f"            ({V(a, -1)} {V(b, -1)} {V(b, +1)} {V(a, +1)})\n")
    out.append("        );\n    }\n")
    for patch, pl in (("front", +1), ("back", -1)):
        out.append(f"    {patch}\n    {{\n        type wedge;\n        faces\n        (\n")
        for nm, names, *_ in blocks:
            out.append("            (" + " ".join(str(V(q, pl)) for q in names) + ")\n")
        out.append("        );\n    }\n")
    out.append(");\n\nmergePatchPairs\n(\n);\n")
    return "".join(out), nc * nc + 3 * nr * nc


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--design", default=None, help="r0 | r1 | r2 (omit for V0_tan2009)")
    ap.add_argument("--scenario", required=True)
    ap.add_argument("--cells", type=int, default=None, help="cells across the radius")
    ap.add_argument("--wall-T", type=float, default=None, help="override wall temperature C")
    ap.add_argument("--h", type=float, default=None, help="override h (W/m2K) for convective bc")
    ap.add_argument("--cu", type=float, default=None)
    ap.add_argument("--q", type=float, default=None)
    ap.add_argument("--mu-scale", type=float, default=1.0)
    ap.add_argument("--beta-scale", type=float, default=1.0)
    ap.add_argument("--init-dt", type=float, default=0.05, help="initial time step s (stiff Darcy constants need ~1e-4)")
    ap.add_argument("--max-co", type=float, default=None)
    ap.add_argument("--conduction-only", action="store_true", help="g = 0 and beta = 0: pure-conduction check of the latent-heat source")
    ap.add_argument("--glass-t", type=float, default=None, help="fixedWall only: put a wall layer of this thickness (m) between the fixed outer T and the PCM")
    ap.add_argument("--glass-k", type=float, default=1.1, help="conductivity of that layer, W/mK (ASSUMED borosilicate glass, not in Tan 2009)")
    ap.add_argument("--h-ext", type=float, default=1e5, help="glass-wall case: outer heat-transfer coefficient W/m2K (1e5 = ideal bath)")
    ap.add_argument("--tag", default="")
    ap.add_argument("--out", default=os.path.join(ROOT, "cases"))
    ap.add_argument("--config", default=os.path.join(ROOT, "configs", "rj_cases.yaml"))
    a = ap.parse_args()

    cfg = yaml.safe_load(open(a.config, encoding="utf-8"))
    sc = dict(cfg["scenarios"][a.scenario])
    of = cfg["openfoam"]
    if a.design:
        des = cfg["designs"][a.design]
        pcm, R = des["pcm"], des["inner_radius_m"]
    else:
        pcm, R = sc["pcm"], sc["radius_m"]
    props = dict(cfg["pcm_properties"][pcm])
    missing = [k for k in REQ if props.get(k) is None]
    if missing:
        fail(f"PCM '{pcm}' has null properties {missing}; source them first (database / paper / datasheet).")
    if R is None:
        fail("radius is null for this scenario")
    props["mu_Pa_s"] *= a.mu_scale
    props["beta_1_K"] *= a.beta_scale
    if a.conduction_only:
        props["beta_1_K"] = 0.0
    if sc.get("wall_from") == "mains_regime_C":
        sc["T_wall_C"] = cfg["mains_regime_C"][a.design]
    if a.wall_T is not None:
        sc["T_wall_C"] = a.wall_T
    if a.h is not None:
        sc["h_W_m2K"] = a.h
    for k in ("T_init_C", "end_time_s"):
        if sc.get(k) is None:
            fail(f"scenario '{a.scenario}' has null {k}")
    if sc["bc"] == "fixedWall" and sc.get("T_wall_C") is None:
        fail("T_wall_C is null")
    if sc["bc"] == "convective" and (sc.get("h_W_m2K") is None or sc.get("T_water_C") is None):
        fail("convective scenario needs h_W_m2K and T_water_C (take h from the simulator at the design flow)")

    n = a.cells or of["cells_radial"]
    cu = float(a.cu if a.cu is not None else of["Cu"])
    q = float(a.q if a.q is not None else of["q"])
    Tm = props["Tm_C"] + K0
    rho = props["rho_solid"]
    cp = 0.5 * (props["cp_solid"] + props["cp_liquid"])
    k = 0.5 * (props["k_solid"] + props["k_liquid"])
    mu, beta = props["mu_Pa_s"], props["beta_1_K"]
    T0 = sc["T_init_C"] + K0
    t_end = sc["end_time_s"]
    name = f"{a.design or 'lit'}_{a.scenario}_n{n}" + (f"_{a.tag}" if a.tag else "")
    c = os.path.join(a.out, name)
    for d in ("0", "constant", "system"):
        os.makedirs(os.path.join(c, d), exist_ok=True)

    def w(rel, txt):
        with open(os.path.join(c, rel), "w", encoding="utf-8", newline="\n") as f:
            f.write(txt)

    bm, ncell = block_mesh(R, n, of["wedge_angle_deg"], of["radial_grading"])
    w("system/blockMeshDict", foam("dictionary", "blockMeshDict", bm))
    w("constant/thermophysicalProperties", foam("dictionary", "thermophysicalProperties", f"""
thermoType {{ type heRhoThermo; mixture pureMixture; transport const; thermo hConst;
             equationOfState Boussinesq; specie specie; energy sensibleEnthalpy; }}
pRef 100000;
mixture
{{
    specie {{ molWeight 250; }}
    equationOfState {{ rho0 {rho:.8g}; T0 {Tm:.8g}; beta {beta:.8g}; }}
    thermodynamics {{ Cp {cp:.8g}; Hf 0; }}
    transport {{ mu {mu:.8g}; Pr {mu * cp / k:.8g}; }}
}}"""))
    w("constant/turbulenceProperties", foam("dictionary", "turbulenceProperties", "simulationType laminar;"))
    w("constant/g", foam("uniformDimensionedVectorField", "g", f"dimensions [0 1 -2 0 0 0 0];\nvalue ({0.0 if a.conduction_only else -9.81} 0 0);"))
    w("constant/fvOptions", foam("dictionary", "fvOptions", f"""
solidificationMeltingSource1
{{
    type            solidificationMeltingSource;
    selectionMode   all;
    Tmelt           {Tm:.8g};
    L               {props['latent_J_kg']:.8g};
    thermoMode      thermo;
    rhoRef          {rho:.8g};
    beta            {beta:.8g};
    Cu              {cu:.8g};
    q               {q:.8g};
    relax           0.9;
}}"""))

    wedge = "    front { type wedge; }\n    back { type wedge; }\n"
    if sc["bc"] == "fixedWall" and a.glass_t:
        wallT = ("        type externalWallHeatFluxTemperature;\n        mode coefficient;\n"
                 f"        Ta constant {sc['T_wall_C'] + K0:.8g};\n        h constant {a.h_ext:.8g};\n"
                 f"        thicknessLayers ({a.glass_t});\n        kappaLayers ({a.glass_k});\n"
                 f"        kappaMethod fluidThermo;\n        value uniform {T0:.8g};")
    elif sc["bc"] == "fixedWall":
        wallT = f"        type fixedValue;\n        value uniform {sc['T_wall_C'] + K0:.8g};"
    else:
        wl = cfg["capsule_wall"]
        wallT = (f"        type externalWallHeatFluxTemperature;\n        mode coefficient;\n"
                 f"        Ta constant {sc['T_water_C'] + K0:.8g};\n        h constant {sc['h_W_m2K']:.8g};\n"
                 f"        thicknessLayers ({wl['thickness_m']});\n        kappaLayers (205);\n"
                 f"        kappaMethod fluidThermo;\n        value uniform {T0:.8g};")
    w("0/T", foam("volScalarField", "T", f"dimensions [0 0 0 1 0 0 0];\ninternalField uniform {T0:.8g};\nboundaryField\n{{\n    wall\n    {{\n{wallT}\n    }}\n{wedge}}}"))
    w("0/U", foam("volVectorField", "U", f"dimensions [0 1 -1 0 0 0 0];\ninternalField uniform (0 0 0);\nboundaryField\n{{\n    wall {{ type noSlip; }}\n{wedge}}}"))
    for fld, bc in (("p_rgh", "fixedFluxPressure"), ("p", "calculated")):
        w(f"0/{fld}", foam("volScalarField", fld, f"dimensions [1 -1 -2 0 0 0 0];\ninternalField uniform 100000;\nboundaryField\n{{\n    wall {{ type {bc}; value uniform 100000; }}\n{wedge}}}"))
    if T0 > Tm + 0.5:      # starts liquid (discharge): the fvOption's liquid-fraction field must start at 1, not 0
        w("0/solidificationMeltingSource1:alpha1", foam("volScalarField", "solidificationMeltingSource1:alpha1",
          f"dimensions [0 0 0 0 0 0 0];\ninternalField uniform 1;\nboundaryField\n{{\n    wall {{ type zeroGradient; }}\n{wedge}}}"))

    fo = lambda nm, body: (f"    {nm}\n    {{\n        libs (fieldFunctionObjects);\n{body}\n        writeFields no;\n        log no;\n"
                           f"        writeControl adjustableRunTime;\n        writeInterval {of['sample_every_s']};\n    }}\n")
    w("system/controlDict", foam("dictionary", "controlDict", f"""
application buoyantPimpleFoam;
startFrom startTime; startTime 0; stopAt endTime; endTime {t_end};
deltaT {a.init_dt}; adjustTimeStep yes; maxCo {a.max_co if a.max_co else of['max_co']}; maxDeltaT {of['max_delta_t_s']};
writeControl adjustableRunTime; writeInterval {of['write_interval_s']}; purgeWrite 0;
writeFormat ascii; writePrecision 8; timeFormat general; timePrecision 8; runTimeModifiable true;
functions
{{
{fo('meltAndTemp', '        type volFieldValue; regionType all; operation volAverage; weightField rho;' + chr(10) + '        fields (T "solidificationMeltingSource1:alpha1");')}
{fo('maxU', '        type volFieldValue; regionType all; operation max; fields (U);')}
{fo('wallFlux', '        type wallHeatFlux; patches (wall);')}
{fo('wallQ', '        type surfaceFieldValue; regionType patch; name wall; operation areaIntegrate; fields (wallHeatFlux);')}
}}"""))
    w("system/fvSchemes", foam("dictionary", "fvSchemes", """
ddtSchemes { default Euler; }
gradSchemes { default Gauss linear; }
divSchemes
{
    default none;
    div(phi,U) Gauss linearUpwind grad(U);
    div(phi,h) Gauss upwind;
    div(phi,K) Gauss linear;
    div(phi,Ekp) Gauss linear;
    div(((rho*nuEff)*dev2(T(grad(U))))) Gauss linear;
}
laplacianSchemes { default Gauss linear corrected; }
interpolationSchemes { default linear; }
snGradSchemes { default corrected; }"""))
    w("system/fvSolution", foam("dictionary", "fvSolution", """
solvers
{
    "rho.*" { solver diagonal; }
    p_rgh { solver PCG; preconditioner DIC; tolerance 1e-8; relTol 0.01; }
    p_rghFinal { $p_rgh; relTol 0; }
    "(U|h)" { solver PBiCGStab; preconditioner DILU; tolerance 1e-8; relTol 0.01; }
    "(U|h)Final" { $U; relTol 0; }
}
PIMPLE { momentumPredictor yes; nOuterCorrectors 1; nCorrectors 2; nNonOrthogonalCorrectors 0; pRefCell 0; pRefValue 100000; }"""))
    w("Allrun", '#!/bin/sh\ncd "${0%/*}" || exit 1\n. ${WM_PROJECT_DIR:?}/bin/tools/RunFunctions\n'
                "runApplication blockMesh\nrunApplication checkMesh -allGeometry -allTopology\nrunApplication $(getApplication)\ntouch case.foam\n")
    os.chmod(os.path.join(c, "Allrun"), 0o755)
    w("case_meta.yaml", yaml.safe_dump({
        "design": a.design, "scenario": a.scenario, "pcm": pcm, "R_m": R, "cells_radial": n, "n_cells_est": ncell,
        "Tsol_K": Tm - cfg["melting_half_width_K"], "Tliq_K": Tm + cfg["melting_half_width_K"], "Tmelt_K_cfd": Tm,
        "props": props, "bc": sc, "Cu": cu, "q": q, "init_dt": a.init_dt, "max_co": a.max_co or of["max_co"], "conduction_only": a.conduction_only, "glass_t": a.glass_t, "glass_k": a.glass_k, "mu_scale": a.mu_scale, "beta_scale": a.beta_scale,
        "note": "single-phase Boussinesq; isothermal melting at Tm; rho0 = density_solid; mean cp, one k; no volume change; no wall mass"}))
    print(c)


if __name__ == "__main__":
    main()
