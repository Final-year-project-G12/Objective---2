    s.append(md(pd.DataFrame(rows)) + "\n")
    pos = an[an.regime.isin(meaningful)].groupby(["regime", "role", "pcm", "anchor", "purpose"]).g_window.mean()
    big = [c for c in REGIMES if rngs[c] > band[c]]
