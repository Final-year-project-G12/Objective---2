def md(df):
    cols = list(df.columns)
    lines = ["| " + " | ".join(cols) + " |", "|" + "|".join("---" for _ in cols) + "|"]
    for r in df.itertuples(index=False):
        lines.append("| " + " | ".join(str(x) for x in r) + " |")
    return "\n".join(lines)


def _clean(name):
    return str(name).replace("�", "").replace("®", "")


def _rng(vals, nd=1, unit=""):
    v = [x for x in vals if pd.notna(x)]
    if not v:
        return "n/a"
    lo, hi = min(v), max(v)
    return f"{lo:+.{nd}f}{unit}" if abs(hi - lo) < 10 ** -nd else f"{lo:+.{nd}f} to {hi:+.{nd}f}{unit}"


def _val(d, block, level, col="g_window"):
    x = d[(d.block == block) & (d.level == level)]
    return float(x[col].iloc[0]) if len(x) and pd.notna(x[col].iloc[0]) else np.nan


def _f(x, nd=1):
    return "-" if pd.isna(x) else f"{x:.{nd}f}"


