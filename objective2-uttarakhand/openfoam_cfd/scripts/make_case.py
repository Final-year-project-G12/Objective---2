#!/usr/bin/env python3
"""
make_case.py -- write one complete OpenFOAM (ESI v2406) case for ONE spherical
PCM capsule being charged by tank water, axisymmetric, melting resolved.

WHAT THIS CASE MODELS
---------------------
One PCM-filled aluminium sphere of diameter d, axis vertical (gravity along the
symmetry axis), initially solid at T_init. The tank water outside is a boundary
condition, not meshed:

    q'' = (T_wall_inner - T_water) / ( 1/h_w + t_al/k_al )

h_w comes from the SAME Wakao-Kaguei packed-bed correlation the Python grey-box
uses (src/simulation/heat_transfer.py), evaluated at the design's flow rate,
tank cross-section and capsule diameter. The aluminium shell enters through the
BC's thicknessLayers/kappaLayers. Inside the shell the PCM is resolved with:

    buoyantPimpleFoam + Boussinesq buoyancy + solidificationMeltingSource
    (Voller-Prakash enthalpy-porosity, Darcy damping in the mushy zone)

so natural convection in the melt is SOLVED, not multiplied in. That is what
the grey-box approximates with "R_pcm = r/(5k)" and "liquid_convection_
enhancement = 2.0" (system_config_shared.yaml) -- both documented there as
unvalidated. The CFD output calibrates / checks exactly those two numbers.

WHAT IT DOES NOT MODEL (be honest in the paper)
-----------------------------------------------
* Tank-scale flow, stratification, other capsules, arrangement (see
  run_arrangement_2d.py for the arrangement study).
* Volume change on melting (rho from the Boussinesq EoS only).
* Supercooling / hysteresis; melting is isothermal at Tm (grey-box uses a
  +/-1 K band).
* Liquid viscosity and expansion are [ASSUMED] -- not in the O1 database.

Usage:
  python make_case.py --out ../cases/demo --pcm RT44HC --d 0.06 --mdot 0.03 --dT 15
"""
import argparse
import math
import os
import sys
import csv
import json
import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)                      # openfoam_cfd/
DEFAULT_CFG = os.path.join(ROOT, "config", "o2_cfd_config_uttarakhand.yaml")

K0 = 273.15
HEADER = r"""/*--------------------------------*- C++ -*----------------------------------*\
  =========                 |
  \\      /  F ield         | OpenFOAM: The Open Source CFD Toolbox
   \\    /   O peration     | Objective 2 (Uttarakhand) PCM capsule CFD
    \\  /    A nd           | generated by make_case.py -- edit the generator,
     \\/     M anipulation  | not this file
\*---------------------------------------------------------------------------*/
"""


def foam_file(cls, obj, body, location=None):
    loc = f'    location    "{location}";\n' if location else ""
    return (HEADER + "FoamFile\n{\n    version     2.0;\n    format      ascii;\n"
            f"    class       {cls};\n{loc}    object      {obj};\n}}\n"
            "// * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * //\n\n"
            + body.rstrip() + "\n\n// ************************************************************************* //\n")


# --------------------------------------------------------------------------
# inputs
# --------------------------------------------------------------------------
def load_cfg(path=DEFAULT_CFG):
    with open(path, "r", encoding="utf-8") as f:
        return yaml.safe_load(f)


def load_pcm(cfg, name):
    sys.path.insert(0, HERE)
    import _paths
    csv_path = _paths.pcm_database()
    with open(csv_path, "r", encoding="utf-8-sig") as f:
        for r in csv.DictReader(f):
            if r["name"].strip().lower() == name.strip().lower() or \
               name.strip().lower() in r["name"].strip().lower():
                def num(key, alt=None):
                    v = r.get(key, "")
                    if v in ("", None, "nan", "NaN"):
                        v = r.get(alt, "") if alt else ""
                    return float(v)
                return dict(
                    name=r["name"], Tm_C=num("Tm_C"), L_kJ_kg=num("latent_heat_kJ_kg"),
                    rho_s=num("density_solid_kg_m3", "density_liquid_kg_m3"),
                    rho_l=num("density_liquid_kg_m3", "density_solid_kg_m3"),
                    cp_s=num("Cp_solid_kJ_kgK", "Cp_avg_kJ_kgK") * 1000.0,
                    cp_l=num("Cp_liquid_kJ_kgK", "Cp_avg_kJ_kgK") * 1000.0,
                    k=num("TC_W_mK"))
    raise SystemExit(f"PCM '{name}' not found in {csv_path}")


def wakao_kaguei_h(mdot, d, cfg, tank_volume_L=None):
    """Identical to heat_transfer.water_side_htc_w_m2k (+ tank_model.py:163
    superficial velocity). Returns (h_w, Re, u_sup)."""
    t = cfg["tank"]
    V = (tank_volume_L if tank_volume_L else t["volume_L"]) / 1000.0
    r = t["height_to_diameter_ratio"]
    D = (4.0 * V / (math.pi * r)) ** (1.0 / 3.0)
    A = math.pi / 4.0 * D ** 2
    w = cfg["water"]
    u = mdot / w["density_kg_m3"] / A
    mu = 2.414e-5 * 10 ** (247.8 / (40.0 + K0 - 140.0))
    re = max(w["density_kg_m3"] * u * d / mu, 1e-6)
    nu = 2.0 + 1.1 * re ** 0.6 * w["prandtl"] ** (1.0 / 3.0)
    return nu * w["conductivity_W_mK"] / d, re, u


# --------------------------------------------------------------------------
# mesh: butterfly (core square + 3 arc blocks) half-disk, rotated +/- wedge/2
# --------------------------------------------------------------------------
def blockmesh_dict(R, cell, wedge_deg, grading):
    hw = math.radians(wedge_deg / 2.0)
    s = 0.5 * R                                   # core half-width
    c45 = math.cos(math.radians(45.0))
    # 2D plane points (x along axis, y radial), y >= 0
    P = {
        "P0": (-s, 0.0), "P1": (s, 0.0), "P2": (s, s), "P3": (-s, s),
        "C0": (-R, 0.0), "C1": (R, 0.0),
        "C2": (R * c45, R * c45), "C3": (-R * c45, R * c45),
    }
    verts, vid = [], {}

    def add(name, plane):                         # plane: +1 front, -1 back
        x, y = P[name]
        key = (name, plane if y > 1e-15 else 0)   # axis points are shared
        if key in vid:
            return vid[key]
        z = plane * y * math.sin(hw)
        verts.append((x, y * math.cos(hw), z))
        vid[key] = len(verts) - 1
        return vid[key]

    def quad(names):
        back = [add(n, -1) for n in names]
        front = [add(n, +1) for n in names]
        return back + front

    nc = max(6, int(round(s / cell)))
    nr = max(6, int(round((R - s) / cell)))
    g_out = grading
    g_in = 1.0 / grading
    blocks = [
        # name, corner order (CCW from +z), (n1,n2), grading (g1,g2)
        ("core",  ["P0", "P1", "P2", "P3"], (nc, nc), (1, 1)),
        ("right", ["P1", "C1", "C2", "P2"], (nr, nc), (g_out, 1)),
        ("top",   ["P3", "P2", "C2", "C3"], (nc, nr), (1, g_out)),
        ("left",  ["C0", "P0", "P3", "C3"], (nr, nc), (g_in, 1)),
    ]
    hexes = []
    for nm, names, (n1, n2), (g1, g2) in blocks:
        hexes.append((nm, quad(names), n1, n2, g1, g2))

    def V(name, plane):
        return vid[(name, plane if P[name][1] > 1e-15 else 0)]

    def arc(a, b, ang_deg):
        m = (R * math.cos(math.radians(ang_deg)), R * math.sin(math.radians(ang_deg)))
        out = []
        for plane in (-1, +1):
            ia, ib = V(a, plane), V(b, plane)
            y = m[1]
            z = plane * y * math.sin(hw)
            out.append(f"    arc {ia} {ib} ({m[0]:.9g} {y * math.cos(hw):.9g} {z:.9g})")
        return out

    edges = arc("C1", "C2", 22.5) + arc("C2", "C3", 90.0) + arc("C3", "C0", 157.5)

    body = ["scale   1;\n", "vertices\n(\n"]
    for v in verts:
        body.append(f"    ({v[0]:.9g} {v[1]:.9g} {v[2]:.9g})\n")
    body.append(");\n\nblocks\n(\n")
    for nm, ids, n1, n2, g1, g2 in hexes:
        body.append(f"    // {nm}\n    hex ({' '.join(map(str, ids))}) ({n1} {n2} 1) "
                    f"simpleGrading ({g1:g} {g2:g} 1)\n")
    body.append(");\n\nedges\n(\n" + "\n".join(edges) + "\n);\n\nboundary\n(\n")

    # patches
    def face(names, plane):
        return "(" + " ".join(str(V(n, plane)) for n in names) + ")"

    wall = [("C1", "C2"), ("C2", "C3"), ("C3", "C0")]
    body.append("    wall\n    {\n        type wall;\n        faces\n        (\n")
    for a, b in wall:
        body.append(f"            ({V(a, -1)} {V(b, -1)} {V(b, +1)} {V(a, +1)})\n")
    body.append("        );\n    }\n")
    for patch, plane in (("front", +1), ("back", -1)):
        body.append(f"    {patch}\n    {{\n        type wedge;\n        faces\n        (\n")
        for nm, names, *_ in blocks:
            body.append("            " + face(names, plane) + "\n")
        body.append("        );\n    }\n")
    body.append(");\n\nmergePatchPairs\n(\n);\n")
    cells = nc * nc + nr * nc + nc * nr + nr * nc
    return foam_file("dictionary", "blockMeshDict", "".join(body), None), cells


# --------------------------------------------------------------------------
# main builder
# --------------------------------------------------------------------------
def build_case(out, pcm_name, d, mdot, dT, cfg=None, t_init_below=None,
               tank_volume_L=None, ta_table=None, conduction_only=False,
               overrides=None, t_end_h=None, cell_size_m=None,
               bc_mode="convective", pcm_props=None, t_init_abs_C=None, sample_every_s=None,
               viz=False):
    """bc_mode: 'convective' (default: water h_w + Al shell) or 'isothermal'
    (wall held at Tm+dT, no shell -- used to reproduce published sphere-melting
    experiments, see validate_sphere.py).  pcm_props: full property dict
    (name, Tm_C, L_kJ_kg, rho_s, rho_l, cp_s, cp_l [J/kgK], k) replacing the O1
    database lookup, so benchmark PCMs need not be in the project database."""
    cfg = cfg or load_cfg()
    p = dict(pcm_props) if pcm_props else load_pcm(cfg, pcm_name)
    a = {k: float(v) for k, v in cfg["assumed_liquid_properties"].items()}
    if overrides:
        a.update({k: v for k, v in overrides.items() if k in a})
    sc, nu_ = cfg["scenario"], dict(cfg["numerics"])
    if cell_size_m:
        nu_["cell_size_m"] = float(cell_size_m)
    wall = cfg["capsule_wall"]

    R = d / 2.0
    Tm = p["Tm_C"] + K0
    T_init = (t_init_abs_C + K0) if t_init_abs_C is not None else         Tm - (t_init_below if t_init_below is not None else sc["T_init_C_below_Tm_K"])
    T_hot = Tm + dT
    if bc_mode == "isothermal":
        h_w, Re, u_sup = 0.0, 0.0, 0.0
    else:
        h_w, Re, u_sup = wakao_kaguei_h(mdot, d, cfg, tank_volume_L)
    cp = 0.5 * (p["cp_s"] + p["cp_l"])
    L = p["L_kJ_kg"] * 1000.0
    t_end = (t_end_h if t_end_h else sc["t_end_h"]) * 3600.0
    sample = sample_every_s if sample_every_s else sc["sample_every_s"]

    os.makedirs(os.path.join(out, "0"), exist_ok=True)
    os.makedirs(os.path.join(out, "constant"), exist_ok=True)
    os.makedirs(os.path.join(out, "system"), exist_ok=True)

    def w(rel, txt):
        with open(os.path.join(out, rel), "w", encoding="utf-8", newline="\n") as f:
            f.write(txt)

    # ---- mesh -------------------------------------------------------------
    bm, ncell = blockmesh_dict(R, nu_["cell_size_m"], nu_["wedge_angle_deg"], nu_["radial_grading"])
    w("system/blockMeshDict", bm)

    # ---- thermo -----------------------------------------------------------
    pr = a["dyn_viscosity_Pa_s"] * cp / p["k"]
    w("constant/thermophysicalProperties", foam_file("dictionary", "thermophysicalProperties", f"""
thermoType
{{
    type            heRhoThermo;
    mixture         pureMixture;
    transport       const;
    thermo          hConst;
    equationOfState Boussinesq;
    specie          specie;
    energy          sensibleEnthalpy;
}}

pRef            100000;

mixture
{{
    specie
    {{
        molWeight       250;
    }}
    equationOfState
    {{
        rho0            {p['rho_l']:.6g};
        T0              {Tm:.6g};
        beta            {0.0 if conduction_only else a['thermal_expansion_1_K']:.6g};
    }}
    thermodynamics
    {{
        Cp              {cp:.6g};
        Hf              0;
    }}
    transport
    {{
        mu              {a['dyn_viscosity_Pa_s']:.6g};
        Pr              {pr:.6g};
    }}
}}
"""))
    w("constant/turbulenceProperties", foam_file("dictionary", "turbulenceProperties",
                                                  "simulationType laminar;"))
    g = 0.0 if conduction_only else -9.81
    w("constant/g", foam_file("uniformDimensionedVectorField", "g",
                              f"dimensions      [0 1 -2 0 0 0 0];\nvalue           ({g} 0 0);"))

    w("constant/fvOptions", foam_file("dictionary", "fvOptions", f"""
solidificationMeltingSource1
{{
    type            solidificationMeltingSource;
    selectionMode   all;

    Tmelt           {Tm:.6g};
    L               {L:.6g};
    thermoMode      thermo;
    rhoRef          {p['rho_s']:.6g};
    beta            {a['thermal_expansion_1_K']:.6g};
    Cu              {a['mushy_Cu']:.6g};
    q               {a['mushy_q']:.6g};
    relax           0.9;
}}
"""))

    # ---- fields -----------------------------------------------------------
    wedge_patches = "    front { type wedge; }\n    back  { type wedge; }\n"
    if ta_table:
        pts = "\n".join(f"            ({t:.6g} {T + K0 if T < 200 else T:.6g})" for t, T in ta_table)
        ta_entry = f"Ta              table\n        (\n{pts}\n        );"
    else:
        ta_entry = f"Ta              constant {T_hot:.6g};"
    if bc_mode == "isothermal":
        wall_bc = f"""        type            fixedValue;
        value           uniform {T_hot:.6g};"""
    else:
        wall_bc = f"""        type            externalWallHeatFluxTemperature;
        mode            coefficient;
        {ta_entry}
        h               constant {h_w:.6g};
        thicknessLayers ({wall['thickness_m']:.6g});
        kappaLayers     ({wall['conductivity_W_mK']:.6g});
        kappaMethod     fluidThermo;
        value           uniform {T_init:.6g};"""
    w("0/T", foam_file("volScalarField", "T", f"""
dimensions      [0 0 0 1 0 0 0];
internalField   uniform {T_init:.6g};

boundaryField
{{
    wall
    {{
{wall_bc}
    }}
{wedge_patches}}}
"""))
    w("0/U", foam_file("volVectorField", "U", f"""
dimensions      [0 1 -1 0 0 0 0];
internalField   uniform (0 0 0);

boundaryField
{{
    wall {{ type noSlip; }}
{wedge_patches}}}
"""))
    w("0/p_rgh", foam_file("volScalarField", "p_rgh", f"""
dimensions      [1 -1 -2 0 0 0 0];
internalField   uniform 100000;

boundaryField
{{
    wall {{ type fixedFluxPressure; value uniform 100000; }}
{wedge_patches}}}
"""))
    w("0/p", foam_file("volScalarField", "p", f"""
dimensions      [1 -1 -2 0 0 0 0];
internalField   uniform 100000;

boundaryField
{{
    wall {{ type calculated; value uniform 100000; }}
{wedge_patches}}}
"""))

    # ---- numerics ---------------------------------------------------------
    w("system/controlDict", foam_file("dictionary", "controlDict", f"""
application     buoyantPimpleFoam;

startFrom       startTime;
startTime       0;
stopAt          endTime;
endTime         {t_end:.8g};

deltaT          {nu_['initial_delta_t_s']};
adjustTimeStep  yes;
maxCo           {nu_['max_co']};
maxDeltaT       {nu_['max_delta_t_s']};

writeControl    adjustableRunTime;
writeInterval   {30 if viz else max(sample * 10, 600):.8g};
purgeWrite      {0 if viz else 3};
writeFormat     ascii;
writePrecision  8;
timeFormat      general;
timePrecision   8;
runTimeModifiable true;

functions
{{
    meltAndTemp
    {{
        type            volFieldValue;
        libs            (fieldFunctionObjects);
        regionType      all;
        operation       volAverage;
        weightField     rho;
        fields          (T "solidificationMeltingSource1:alpha1");
        writeFields     no;
        log             no;
        writeControl    adjustableRunTime;
        writeInterval   {sample:.8g};
    }}
    meltExtrema
    {{
        type            volFieldValue;
        libs            (fieldFunctionObjects);
        regionType      all;
        operation       max;
        fields          (T);
        writeFields     no;
        log             no;
        writeControl    adjustableRunTime;
        writeInterval   {sample:.8g};
    }}
    meltMin
    {{
        type            volFieldValue;
        libs            (fieldFunctionObjects);
        regionType      all;
        operation       min;
        fields          (T);
        writeFields     no;
        log             no;
        writeControl    adjustableRunTime;
        writeInterval   {sample:.8g};
    }}
    totalVolume
    {{
        type            volFieldValue;
        libs            (fieldFunctionObjects);
        regionType      all;
        operation       volIntegrate;
        fields          (rho);
        writeFields     no;
        log             no;
        writeControl    onEnd;
    }}
    wallFlux
    {{
        type            wallHeatFlux;
        libs            (fieldFunctionObjects);
        patches         (wall);
        writeFields     no;
        log             no;
        writeControl    adjustableRunTime;
        writeInterval   {sample:.8g};
    }}
    wallQ
    {{
        type            surfaceFieldValue;
        libs            (fieldFunctionObjects);
        regionType      patch;
        name            wall;
        operation       areaIntegrate;
        fields          (wallHeatFlux);
        writeFields     no;
        log             no;
        writeControl    adjustableRunTime;
        writeInterval   {sample:.8g};
    }}
}}
"""))
    w("system/fvSchemes", foam_file("dictionary", "fvSchemes", """
ddtSchemes      { default Euler; }
gradSchemes     { default Gauss linear; }
divSchemes
{
    default         none;
    div(phi,U)      Gauss linearUpwind grad(U);
    div(phi,h)      Gauss upwind;
    div(phi,K)      Gauss linear;
    div(phi,Ekp)    Gauss linear;
    div(((rho*nuEff)*dev2(T(grad(U))))) Gauss linear;
}
laplacianSchemes { default Gauss linear corrected; }
interpolationSchemes { default linear; }
snGradSchemes   { default corrected; }
"""))
    w("system/fvSolution", foam_file("dictionary", "fvSolution", """
solvers
{
    "rho.*"     { solver diagonal; }
    p_rgh
    {
        solver          PCG;
        preconditioner  DIC;
        tolerance       1e-8;
        relTol          0.01;
    }
    p_rghFinal { $p_rgh; relTol 0; }
    "(U|h)"
    {
        solver          PBiCGStab;
        preconditioner  DILU;
        tolerance       1e-8;
        relTol          0.01;
    }
    "(U|h)Final" { $U; relTol 0; }
}
PIMPLE
{
    momentumPredictor   yes;
    nOuterCorrectors    1;
    nCorrectors         2;
    nNonOrthogonalCorrectors 0;
    pRefCell            0;
    pRefValue           100000;
}
"""))

    # run script + metadata
    w("Allrun", "#!/bin/sh\ncd \"${0%/*}\" || exit 1\n"
                ". ${WM_PROJECT_DIR:?}/bin/tools/RunFunctions\n"
                "runApplication blockMesh\nrunApplication checkMesh\n"
                "runApplication $(getApplication)\n")
    os.chmod(os.path.join(out, "Allrun"), 0o755)

    meta = dict(
        pcm=p["name"], Tm_C=p["Tm_C"], L_kJ_kg=p["L_kJ_kg"], rho_s=p["rho_s"], rho_l=p["rho_l"],
        cp_avg=cp, k=p["k"], d_m=d, mdot_kg_s=mdot, dT_K=dT, T_init_C=T_init - K0,
        T_hot_C=T_hot - K0, h_w_W_m2K=h_w, Re_p=Re, u_sup_m_s=u_sup,
        tank_volume_L=tank_volume_L or cfg["tank"]["volume_L"],
        conduction_only=conduction_only, assumed=a, t_end_s=t_end, bc_mode=bc_mode,
        wedge_deg=nu_["wedge_angle_deg"], n_cells_est=ncell, cell_size_m=nu_["cell_size_m"],
        Bi=h_w * R / p["k"], Ste=cp * dT / L, config_version=cfg["version"])
    w("case_meta.json", json.dumps(meta, indent=2))
    return meta


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", required=True)
    ap.add_argument("--pcm", default="RT44HC")
    ap.add_argument("--d", type=float, default=0.06, help="capsule diameter [m]")
    ap.add_argument("--mdot", type=float, default=0.03, help="tank flow rate [kg/s]")
    ap.add_argument("--dT", type=float, default=15.0, help="hot water above Tm [K]")
    ap.add_argument("--t-end-h", type=float, default=None)
    ap.add_argument("--tank-L", type=float, default=None, help="override tank volume (e.g. 112.5)")
    ap.add_argument("--conduction-only", action="store_true",
                    help="g=0, beta=0: pure-conduction baseline (calibrates the x2 factor)")
    ap.add_argument("--viz", action="store_true",
                    help="keep fields every 30 s for ParaView (default keeps only the last 3 write times)")
    ap.add_argument("--config", default=DEFAULT_CFG)
    a = ap.parse_args()
    m = build_case(a.out, a.pcm, a.d, a.mdot, a.dT, cfg=load_cfg(a.config), tank_volume_L=a.tank_L,
                   conduction_only=a.conduction_only, t_end_h=a.t_end_h, viz=a.viz)
    print(json.dumps({k: m[k] for k in ("pcm", "d_m", "h_w_W_m2K", "Re_p", "Bi", "Ste", "n_cells_est")}, indent=2))


if __name__ == "__main__":
    main()
